def aggregate_prediction_summary(keys, results, resampling):
    output = {"dataset": "All", "model": "All", "specifications": len(keys),
              "test_months": len(TEST_MONTHS),
              "unique_source_rows": sum(len(ENSEMBLES[(dataset, CFG["models"][0])]) for dataset in DATASETS)}
    definitions = [
        ("oos_r2", "lo", "hi", "Zero excess return"),
        ("r2_historical_mean", "r2_historical_mean_lo", "r2_historical_mean_hi", "Historical mean"),
        ("r2_cross_sectional", "r2_cross_sectional_lo", "r2_cross_sectional_hi", "Cross-sectional centering"),
    ]
    for metric, lo_name, hi_name, label in definitions:
        points, paired_draws = [], []
        for key in keys:
            item = results[key]
            if metric == "oos_r2":
                numerator, denominator = item["score"][:, 0], item["score"][:, 1]
            elif metric == "r2_historical_mean":
                numerator, denominator = item["score"][:, 0], item["benchmark_score"][:, 0]
            else:
                numerator, denominator = item["benchmark_score"][:, 1], item["benchmark_score"][:, 2]
            points.append(float(1 - numerator.sum() / denominator.sum()) if denominator.sum() > 0 else np.nan)
            sampled_denominator = denominator[resampling].sum(axis=1)
            ratio = np.full(len(resampling), np.nan)
            np.divide(numerator[resampling].sum(axis=1), sampled_denominator,
                      out=ratio, where=sampled_denominator > 0)
            paired_draws.append(1 - ratio)
        macro_draws = np.mean(np.stack(paired_draws), axis=0)
        macro_draws = macro_draws[np.isfinite(macro_draws)]
        output[metric] = float(np.mean(points))
        output[lo_name], output[hi_name] = np.nan, np.nan
        output[f"{metric}_boot_valid"] = len(macro_draws)
        if len(macro_draws) >= BS["min_valid_share"] * BS["reps"]:
            tail = (1 - BS["level"]) / 2
            output[lo_name], output[hi_name] = map(float, np.quantile(
                macro_draws, [tail, 1-tail], method="inverted_cdf"))
    return pd.DataFrame([output])


