class ArtifactSource:
    """Read the user's main-experiment outputs directly from ZIPs or folders."""

    def __init__(self, path, role):
        self.path, self.role = Path(path).expanduser().resolve(), role
        self.archive = zipfile.ZipFile(self.path) if self.path.is_file() else None
        if self.archive is not None:
            self.names = [n for n in self.archive.namelist() if not n.endswith("/")]
            self.signature = digest_file(self.path)
        else:
            self.names = [p.relative_to(self.path).as_posix()
                          for p in self.path.rglob("*") if p.is_file()]
            manifest = []
            for name in sorted(self.names):
                if name.endswith((".joblib", ".json", ".parquet")):
                    stat = (self.path / name).stat()
                    manifest.append((name, stat.st_size, stat.st_mtime_ns))
            self.signature = fingerprint(manifest)

    def member(self, relative):
        if relative in self.names:
            return relative
        matches = [name for name in self.names if name.endswith("/" + relative)]
        if len(matches) == 1:
            return matches[0]
        raise FileNotFoundError(f"{self.role}: required output {relative} was not found uniquely in {self.path.name}.")

    def has(self, relative):
        try:
            self.member(relative)
            return True
        except FileNotFoundError:
            return False

    def read_bytes(self, relative):
        member = self.member(relative)
        return self.archive.read(member) if self.archive else (self.path / member).read_bytes()

    def read_json(self, relative):
        return json.loads(self.read_bytes(relative).decode("utf-8"))

    def read_csv(self, relative):
        return pd.read_csv(io.BytesIO(self.read_bytes(relative)))

    def read_joblib(self, relative):
        return joblib.load(io.BytesIO(self.read_bytes(relative)))

    def describe(self):
        return {"role": self.role, "path": str(self.path), "signature": self.signature}

    def close(self):
        if self.archive:
            self.archive.close()


