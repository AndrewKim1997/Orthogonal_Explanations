def plot_interval(ax, block, x_column, style):
    block = block.sort_values(x_column)
    x = block[x_column].to_numpy(float)
    y, lo, hi = [block[column].to_numpy(float) for column in ["mean", "lo", "hi"]]
    # Preserve unsupported positions as gaps; diagnostics remain in the tables.
    ax.plot(x, np.where(np.isfinite(y), y, np.nan), **style)
    band = np.isfinite(y) & np.isfinite(lo) & np.isfinite(hi)
    ax.fill_between(x, lo, hi, where=band, color=style["color"], alpha=0.12)


