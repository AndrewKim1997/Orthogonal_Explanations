def stationary_indices(months, repetitions, seed):
    length = max(2, int(round(months ** (1 / 3)))) if BS["block"] is None else int(BS["block"])
    length = min(max(1, length), months)
    rng = np.random.default_rng(seed)
    index = np.empty((repetitions, months), int)
    index[:, 0] = rng.integers(0, months, repetitions)
    for t in range(1, months):
        restart = rng.random(repetitions) < 1 / length
        index[:, t] = np.where(restart, rng.integers(0, months, repetitions), (index[:, t - 1] + 1) % months)
    return index, length


def summarize_monthly(series, resampling):
    series = np.asarray(series, float)
    count = int(np.isfinite(series).sum())
    output = {"mean": float(series[np.isfinite(series)].mean()) if count else np.nan,
              "se": np.nan, "lo": np.nan, "hi": np.nan, "p": np.nan,
              "months": count, "bootstrap_valid": 0, "status": "Few supported months"}
    if count < BS["min_months"]:
        return output
    samples = series[resampling]
    finite = np.isfinite(samples)
    denominator = finite.sum(axis=1)
    draws = np.full(len(samples), np.nan)
    np.divide(np.where(finite, samples, 0).sum(axis=1), denominator, out=draws,
              where=denominator >= max(3, BS["min_months"] // 2))
    draws = draws[np.isfinite(draws)]
    output["bootstrap_valid"] = len(draws)
    if len(draws) < BS["min_valid_share"] * len(resampling):
        output["status"] = "Sparse supported resamples"
        return output
    output["lo"], output["hi"] = map(float, percentile_bounds(draws))
    output["se"] = float(draws.std(ddof=1))
    exceedances = int(np.sum(np.abs(draws - output["mean"]) >= abs(output["mean"])))
    output["p"] = (1 + exceedances) / (1 + len(draws))
    output["status"] = "OK"
    return output


def holm_adjust(pvalues):
    values = np.asarray(pvalues, float)
    filled = np.where(np.isfinite(values), values, 1.0)
    order = np.argsort(filled, kind="stable")
    adjusted = np.minimum(1.0, np.maximum.accumulate(filled[order] * np.arange(len(values), 0, -1)))
    output = np.empty(len(values))
    output[order] = adjusted
    output[~np.isfinite(values)] = np.nan
    return output


