    def sort_returns(signal, outcome, groups):
        if len(signal) < groups * SPEC["min_bin"]:
            return np.full(groups, np.nan), np.zeros(groups, int), "Few portfolios"
        cuts = np.quantile(signal, np.arange(1, groups) / groups)
        if len(np.unique(cuts)) != groups - 1:
            return np.full(groups, np.nan), np.zeros(groups, int), "Tied cuts"
        assignment = np.searchsorted(cuts, signal, side="left")
        sizes = np.bincount(assignment, minlength=groups)
        if sizes.min() < SPEC["min_bin"]:
            return np.full(groups, np.nan), sizes, "Small group"
        return np.array([outcome[assignment == group].mean() for group in range(groups)]), sizes, "OK"


    def two_way_demean(values, entities, dates):
        residual = np.asarray(values, float).copy()
        groups = [np.asarray(entities, int), np.asarray(dates, int)]
        counts = [np.bincount(group) for group in groups]
        tolerance = SPEC["within_tol"] * max(1.0, float(np.abs(residual).max()))
        for iteration in range(SPEC["within_max_iter"]):
            previous = residual.copy()
            for group, count in zip(groups, counts):
                sums = np.zeros((len(count), residual.shape[1]))
                np.add.at(sums, group, residual)
                residual -= (sums / count[:, None])[group]
            if float(np.abs(residual - previous).max()) <= tolerance:
                return residual, iteration + 1
        return None, SPEC["within_max_iter"]


    def cluster_meat(scores, group):
        labels, inverse = np.unique(group, return_inverse=True)
        sums = np.zeros((len(labels), scores.shape[1]))
        np.add.at(sums, inverse, scores)
        return sums.T @ sums, len(labels)


    def twfe_cluster_grid(frame, z, kind, run_seed):
        n, k = z.shape
        entity, entity_labels = pd.factorize(frame["id"], sort=True)
        date, date_labels = pd.factorize(frame["return_date"], sort=True)
        ne, nt = len(entity_labels), len(date_labels)
        base = {"model": kind, "seed": run_seed, "rows": n, "entities": ne, "months": nt}
        rows = [{**base, "covariance": covariance, "feature": feature,
            "mean": np.nan, "se": np.nan, "lo": np.nan, "hi": np.nan, "p": np.nan, "status": "Unsupported"}
            for covariance in SPEC["twfe_covariances"] for feature in FEATURES]
        if ne < 2 or nt < BS["min_months"]:
            return rows
        within, iterations = two_way_demean(np.column_stack([frame["y"].to_numpy(float), z]), entity, date)
        if within is None:
            for row in rows:
                row["status"] = "Within transformation did not converge"
            return rows
        outcome, full_design = within[:, 0], within[:, 1:]
        active = np.flatnonzero(full_design.std(axis=0) > 1e-12)
        if not len(active):
            return rows
        design = full_design[:, active]
        _, singular, right_vectors = np.linalg.svd(design, full_matrices=False)
        if singular[-1] <= CFG["rank_tol"] * singular[0]:
            for row in rows:
                row["status"] = "Within design rank deficient"
            return rows
        adjacency = sparse.coo_matrix((np.ones(2 * n),
            (np.r_[entity, ne + date], np.r_[ne + date, entity])), shape=(ne + nt, ne + nt)).tocsr()
        components = connected_components(adjacency, directed=False, return_labels=False)
        absorbed_rank = ne + nt - int(components)
        residual_df = n - absorbed_rank - len(active)
        if residual_df <= 0:
            return rows
        beta = np.linalg.lstsq(design, outcome, rcond=CFG["rank_tol"])[0]
        residual = outcome - design @ beta
        scores = design * residual[:, None]
        terms = [cluster_meat(scores, group) for group in [entity, date, entity.astype(np.int64) * nt + date]]
        corrected = [meat * (clusters / (clusters - 1)) * ((n - 1) / residual_df) for meat, clusters in terms]
        bread = (right_vectors.T / np.square(singular)) @ right_vectors
        covariances = {"Entity": (bread @ corrected[0] @ bread, ne - 1),
                       "Month": (bread @ corrected[1] @ bread, nt - 1),
                       "Two-way": (bread @ (corrected[0] + corrected[1] - corrected[2]) @ bread, min(ne, nt) - 1)}
        for covariance_name, (covariance, degrees) in covariances.items():
            diagonal = np.diag((covariance + covariance.T) / 2)
            critical = float(student_t.ppf(1 - (1 - BS["level"]) / 2, degrees))
            for position, j in enumerate(active):
                row = rows[SPEC["twfe_covariances"].index(covariance_name) * k + j]
                row.update({"mean": float(beta[position]), "inference_df": degrees,
                    "absorbed_rank": absorbed_rank, "residual_df": residual_df, "within_iterations": iterations})
                if not np.isfinite(diagonal[position]) or diagonal[position] <= 0:
                    row["status"] = "Nonpositive clustered variance"
                    continue
                se = math.sqrt(float(diagonal[position]))
                row.update({"se": se, "lo": float(beta[position] - critical * se), "hi": float(beta[position] + critical * se),
                    "p": float(2 * student_t.sf(abs(beta[position] / se), degrees)), "status": "OK"})
        return rows


