def linearmodels_estimates(fit):
    intervals = fit.conf_int()
    rows = []
    for term in fit.params.index:
        row = {"term": term, "coef": float(fit.params.loc[term]),
               "se": float(fit.std_errors.loc[term]), "statistic": float(fit.tstats.loc[term]),
               "pvalue": float(fit.pvalues.loc[term]),
               "lower": float(intervals.loc[term].iloc[0]),
               "upper": float(intervals.loc[term].iloc[1])}
        rows.append(check_estimate(row, term))
    return pd.DataFrame(rows)


