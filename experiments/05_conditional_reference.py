def read_french_block(payload, expected_columns, value_weighted=False):
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        members = [n for n in archive.namelist() if n.lower().endswith(".csv") and "__MACOSX" not in n]
        if len(members) != 1:
            raise ValueError("Expected one French source CSV per ZIP.")
        content = archive.read(members[0]).decode("utf-8-sig", errors="replace")
    armed, header, dates, values = not value_weighted, None, [], []
    for line in content.splitlines():
        title = line.lower().replace("-", " ")
        if value_weighted and all(word in title for word in ["value", "weighted", "monthly"]):
            armed = True
            continue
        if not armed:
            continue
        fields = [s.strip() for s in next(csv.reader([line]))] if line.strip() else []
        while len(fields) > expected_columns + 1 and fields[-1] == "":
            fields.pop()
        first = fields[0] if fields else ""
        if len(first) == 6 and first.isdigit():
            if header is None or len(fields) != expected_columns + 1:
                raise ValueError("Unexpected row in the French monthly return table.")
            dates.append(first)
            values.append([float(v) if v else np.nan for v in fields[1:]])
        elif dates:
            break
        elif len(fields) == expected_columns + 1 and first.lower() in {"", "date"} and all(fields[1:]):
            header = fields[1:]
    if not dates or header is None:
        raise ValueError("The requested French monthly table was not found.")
    array = np.asarray(values, float)
    missing = np.isclose(array, -99.99, rtol=0, atol=1e-8) | np.isclose(array, -999, rtol=0, atol=1e-8)
    array[missing] = np.nan
    return pd.DataFrame(array / 100, index=pd.to_datetime(dates, format="%Y%m").to_period("M"), columns=header).sort_index()


def fetch_french_file(specification, expected_hash=None):
    candidates = [BASE_DIR / "ff100_cache" / "raw" / specification["file"], RAW_DIR / specification["file"]]
    existing = [path for path in candidates if path.is_file() and zipfile.is_zipfile(path)]
    matching = [path for path in existing if expected_hash and digest_file(path) == expected_hash]
    if matching or existing:
        path = (matching or existing)[0]
        log("Cache", f"Using {specification['file']}")
        return path
    path = RAW_DIR / specification["file"]
    temporary = path.with_suffix(".zip.partial")
    for attempt in range(1, 4):
        log("Download", f"{specification['file']}: attempt {attempt}")
        try:
            request = Request(specification["url"], headers={"User-Agent": "Mozilla/5.0", "Accept": "application/zip,*/*"})
            with urlopen(request, timeout=60) as response, temporary.open("wb") as target:
                while True:
                    chunk = response.read(1024 * 1024)
                    if not chunk:
                        break
                    target.write(chunk)
            if not zipfile.is_zipfile(temporary):
                raise ValueError("The French source response must be a CSV ZIP archive.")
            temporary.replace(path)
            return path
        except Exception:
            temporary.unlink(missing_ok=True)
            if attempt == 3:
                raise
            time.sleep(attempt)


