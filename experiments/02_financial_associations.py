def valid_french_zip(path):
    if not path.is_file() or not zipfile.is_zipfile(path):
        return False
    try:
        with zipfile.ZipFile(path) as archive:
            return any(name.lower().endswith(".csv") for name in archive.namelist())
    except (OSError, zipfile.BadZipFile):
        return False


def download_french_zip(url, filename):
    path = CACHE_DIR / "raw" / filename
    path.parent.mkdir(parents=True, exist_ok=True)
    if valid_french_zip(path):
        log("Cache", f"Using {filename}")
        return path
    temporary = path.with_suffix(".zip.partial")
    error = None
    for attempt in range(DATA["download_retries"] + 1):
        try:
            log("Download", filename)
            request = Request(url, headers={"User-Agent": "Mozilla/5.0", "Accept": "application/zip,*/*"})
            with urlopen(request, timeout=60) as response, temporary.open("wb") as target:
                while True:
                    chunk = response.read(1024 * 1024)
                    if not chunk:
                        break
                    target.write(chunk)
            if not valid_french_zip(temporary):
                raise ValueError(f"The source did not return a valid CSV ZIP archive: {filename}")
            temporary.replace(path)
            return path
        except Exception as exc:
            error = exc
            temporary.unlink(missing_ok=True)
            log("Download", f"Attempt {attempt + 1} failed: {exc}")
            if attempt < DATA["download_retries"]:
                time.sleep(min(2 ** (attempt + 1), 8))
    raise RuntimeError(f"French Data Library download failed: {filename}") from error


def read_french_monthly_block(path, expected_columns, value_weighted=False):
    """Read one explicitly identified monthly block; exclude annual/EW tables."""
    with zipfile.ZipFile(path) as archive:
        members = [name for name in archive.namelist()
                   if name.lower().endswith(".csv") and "__MACOSX" not in name]
        if len(members) != 1:
            raise ValueError(f"Expected one CSV inside {path.name}; found {members}")
        payload = archive.read(members[0])
    try:
        content = payload.decode("utf-8-sig")
    except UnicodeDecodeError:
        content = payload.decode("latin-1")
    armed = not value_weighted
    header, dates, rows = None, [], []
    for line in content.splitlines():
        title = re.sub(r"[-\s]+", " ", line.lower()).strip()
        if value_weighted and all(word in title for word in ["value", "weighted", "monthly"]):
            armed = True
            continue
        if not armed:
            continue
        fields = [field.strip() for field in next(csv.reader([line]))] if line.strip() else []
        while len(fields) > expected_columns + 1 and fields[-1] == "":
            fields.pop()
        first = fields[0] if fields else ""
        is_month = len(first) == 6 and first.isdigit()
        if is_month:
            if header is None or len(fields) != expected_columns + 1:
                raise ValueError(f"Invalid monthly header/row in {path.name}: {line[:100]}")
            dates.append(first)
            rows.append([float(value) if value else np.nan for value in fields[1:]])
        elif dates:
            break
        elif (len(fields) == expected_columns + 1 and first.lower() in {"", "date"}
              and all(fields[1:])):
            header = fields[1:]
    if not rows or header is None or len(set(header)) != expected_columns:
        raise ValueError(f"Required monthly block was not found in {path.name}.")
    values = np.asarray(rows, dtype=float)
    missing = np.isclose(values, -99.99, rtol=0, atol=1e-8) | np.isclose(values, -999.0, rtol=0, atol=1e-8)
    values[missing] = np.nan
    # Official return and RF tables are percentages. Convert once to decimals.
    monthly_index = pd.to_datetime(dates, format="%Y%m", errors="raise").to_period("M")
    frame = pd.DataFrame(values / 100.0, index=monthly_index, columns=header)
    if frame.index.duplicated().any():
        raise ValueError(f"Duplicate monthly dates in {path.name}.")
    return frame.sort_index(), members[0]


