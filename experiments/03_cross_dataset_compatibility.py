def download_file(url, path, expected_sha256=None, expected_bytes=None, git_blob=None, progress=False):
    """Cache exact source bytes, retry failed transfers and validate pinned identities."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    def acceptable(candidate):
        if not candidate.is_file() or candidate.stat().st_size == 0:
            return False
        if expected_bytes is not None and candidate.stat().st_size != expected_bytes:
            return False
        if expected_sha256 and digest_file(candidate) != expected_sha256:
            return False
        if git_blob:
            content = candidate.read_bytes()
            value = hashlib.sha1(f"blob {len(content)}\0".encode() + content).hexdigest()
            if value != git_blob:
                return False
        return True

    if acceptable(path):
        if progress:
            log("Cache", f"Using {path.name}")
        return path
    error = None
    temporary = path.with_suffix(path.suffix + ".partial")
    for attempt in range(CFG["download_retries"] + 1):
        try:
            if progress:
                log("Download", f"{path.name}: connecting, attempt {attempt + 1}.")
            request = Request(url, headers={"User-Agent": "Mozilla/5.0", "Accept": "*/*"})
            with urlopen(request, timeout=120) as response, temporary.open("wb") as stream:
                total = int(response.headers.get("Content-Length", 0)) or expected_bytes
                with tqdm(total=total, unit="B", unit_scale=True, desc=path.name,
                          disable=not progress, leave=False) as bar:
                    while True:
                        block = response.read(1024 * 1024)
                        if not block:
                            break
                        stream.write(block)
                        bar.update(len(block))
            if not acceptable(temporary):
                raise ValueError(f"Source integrity check failed: {path.name}")
            temporary.replace(path)
            return path
        except Exception as exc:
            error = exc
            log("Download", f"{path.name}: attempt {attempt + 1} failed ({type(exc).__name__}: {exc}).")
            temporary.unlink(missing_ok=True)
            if attempt < CFG["download_retries"]:
                time.sleep(min(2 ** attempt, 8))
    raise RuntimeError(f"Required data download failed: {url}. No benchmark is substituted or skipped.") from error


