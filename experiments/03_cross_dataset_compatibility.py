def stationary_indices(months, repetitions, seed):
    length = max(2, int(round(months ** (1 / 3)))) if BS["block"] is None else int(BS["block"])
    length = min(max(1, length), months)
    rng = np.random.default_rng(seed)
    indices = np.empty((repetitions, months), int)
    indices[:, 0] = rng.integers(0, months, repetitions)
    for t in range(1, months):
        restart = rng.random(repetitions) < 1 / length
        indices[:, t] = np.where(restart, rng.integers(0, months, repetitions), (indices[:, t-1] + 1) % months)
    return indices, length


def summarize_monthly(values, resampling):
    finite = np.isfinite(values)
    n = int(finite.sum())
    result = {"mean": float(values[finite].mean()) if n else np.nan, "lo": np.nan, "hi": np.nan,
              "se": np.nan, "p": np.nan, "bootstrap_tail_count": np.nan,
              "bootstrap_p_floor": np.nan, "months": n, "boot_valid": 0, "status": "Few supported months"}
    if n < BS["min_months"]:
        return result
    samples = values[resampling]
    counts = np.isfinite(samples).sum(axis=1)
    draws = np.full(len(samples), np.nan)
    np.divide(np.nansum(samples, axis=1), counts, out=draws, where=counts >= max(3, BS["min_months"] // 2))
    draws = draws[np.isfinite(draws)]
    result["boot_valid"] = len(draws)
    if len(draws) < BS["min_valid_share"] * BS["reps"]:
        result["status"] = "Sparse bootstrap resamples"
        return result
    tail = (1 - BS["level"]) / 2
    result["lo"], result["hi"] = map(float, np.quantile(draws, [tail, 1-tail], method="inverted_cdf"))
    result["se"] = float(draws.std(ddof=1))
    exceedances = int(np.sum(np.abs(draws - result["mean"]) >= abs(result["mean"])))
    result["bootstrap_tail_count"] = exceedances
    result["bootstrap_p_floor"] = float(1 / (1 + len(draws)))
    result["p"] = float((1 + exceedances) / (1 + len(draws)))
    result["status"] = "OK"
    return result


def holm_adjust(pvalues):
    pvalues = np.asarray(pvalues, float)
    filled = np.where(np.isfinite(pvalues), pvalues, 1.0)
    order = np.argsort(filled, kind="stable")
    corrected = np.minimum(1.0, np.maximum.accumulate(filled[order] * np.arange(len(filled), 0, -1)))
    output = np.empty(len(filled))
    output[order] = corrected
    output[~np.isfinite(pvalues)] = np.nan
    return output


def prediction_summary(score, resampling, benchmark_score=None):
    output = {"oos_r2": np.nan, "lo": np.nan, "hi": np.nan, "test_rows": int(score[:, 2].sum()),
              "r2_historical_mean": np.nan, "r2_historical_mean_lo": np.nan,
              "r2_historical_mean_hi": np.nan, "r2_cross_sectional": np.nan,
              "r2_cross_sectional_lo": np.nan, "r2_cross_sectional_hi": np.nan}
    if not np.isfinite(score).all():
        return output

    def ratio_interval(numerator, denominator):
        if (not np.isfinite(numerator).all() or not np.isfinite(denominator).all()
                or denominator.sum() <= 0):
            return np.nan, np.nan, np.nan
        point = float(1 - numerator.sum() / denominator.sum())
        sampled_denominator = denominator[resampling].sum(axis=1)
        sampled_ratio = np.full(len(resampling), np.nan)
        np.divide(numerator[resampling].sum(axis=1), sampled_denominator,
                  out=sampled_ratio, where=sampled_denominator > 0)
        draws = 1 - sampled_ratio[np.isfinite(sampled_ratio)]
        lo, hi = np.nan, np.nan
        if len(draws) >= BS["min_valid_share"] * BS["reps"]:
            tail = (1 - BS["level"]) / 2
            lo, hi = map(float, np.quantile(draws, [tail, 1-tail], method="inverted_cdf"))
        return point, lo, hi

    # Retain the original zero-excess-return benchmark as the primary metric.
    output["oos_r2"], output["lo"], output["hi"] = ratio_interval(score[:, 0], score[:, 1])
    if benchmark_score is not None:
        output["r2_historical_mean"], output["r2_historical_mean_lo"], output["r2_historical_mean_hi"] = ratio_interval(
            score[:, 0], benchmark_score[:, 0])
        output["r2_cross_sectional"], output["r2_cross_sectional_lo"], output["r2_cross_sectional_hi"] = ratio_interval(
            benchmark_score[:, 1], benchmark_score[:, 2])
    return output


