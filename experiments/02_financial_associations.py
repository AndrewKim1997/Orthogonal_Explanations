def fit_preprocessor(x, seed):
    # Empty columns in later expanding windows indicate a source/schema error.
    if np.any(np.isfinite(x).sum(axis=0) == 0):
        raise ValueError("An included characteristic is entirely missing in a fitting window.")
    imputer = SimpleImputer(strategy="median")
    filled = imputer.fit_transform(x)
    if DATA["gaussianize"]:
        transform = QuantileTransformer(n_quantiles=min(1000, len(x)),
            output_distribution="normal", subsample=min(DATA["quantile_subsample"], len(x)),
            random_state=seed)
    else:
        transform = StandardScaler()
    transformed = np.asarray(transform.fit_transform(filled), dtype=np.float32)
    return (imputer, transform), transformed

def transform_x(preprocessor, x):
    imputer, transform = preprocessor
    return np.asarray(transform.transform(imputer.transform(x)), dtype=np.float32)

class ReturnPredictor:
    """A common prediction API returning original monthly excess-return units."""

    def __init__(self, estimator, kind, target_mean=0.0, target_scale=1.0):
        self.estimator, self.kind = estimator, kind
        self.target_mean, self.target_scale = target_mean, target_scale

    def predict(self, x):
        x = np.ascontiguousarray(x, dtype=np.float32)
        if self.kind == "XGB":
            pred = self.estimator.get_booster().inplace_predict(x, validate_features=False)
        else:
            pred = self.estimator.predict(x)
        return self.target_mean + self.target_scale * np.asarray(pred, dtype=np.float64)

    def checkpoint(self):
        # Standard sklearn/XGB estimators remain loadable without this wrapper class.
        return {"estimator": self.estimator, "kind": self.kind,
                "target_mean": self.target_mean, "target_scale": self.target_scale}


def make_model(kind, parameter, seed, n_rows):
    if kind == "LR":
        return LinearRegression(fit_intercept=True)
    if kind == "XGB":
        return XGBRegressor(n_estimators=int(parameter), max_depth=CFG["depth"],
            learning_rate=CFG["learning_rate"], objective="reg:squarederror", tree_method="hist",
            device=CFG["device"], subsample=CFG["subsample"], colsample_bytree=CFG["colsample"],
            reg_lambda=1.0, random_state=seed, n_jobs=CFG["n_jobs"])
    if kind == "MLP":
        return MLPRegressor(hidden_layer_sizes=tuple(CFG["mlp_hidden"]), activation="relu",
            solver="adam", alpha=CFG["mlp_alpha"], learning_rate_init=CFG["mlp_learning_rate"],
            batch_size=min(int(CFG["mlp_batch_size"]), int(n_rows)), max_iter=1,
            early_stopping=False, shuffle=True, random_state=seed)
    raise ValueError(f"Unknown prediction model: {kind}")


def fit_with_parameter(kind, x, y, parameter, seed):
    y = np.asarray(y, dtype=np.float64)
    estimator = make_model(kind, parameter, seed, len(y))
    if kind == "MLP":
        location, scale = float(y.mean()), max(float(y.std()), 1e-12)
        scaled_y = (y - location) / scale
        for _ in range(int(parameter)):
            estimator.partial_fit(x, scaled_y)
        return ReturnPredictor(estimator, kind, location, scale)
    estimator.fit(x, y)
    return ReturnPredictor(estimator, kind)


def fit_candidate(xt, yt, xv, yv, run_seed, year, kind):
    """Validation selects trees/epochs; MLP target scaling uses training y only."""
    seed = seed_for(run_seed, 704, year, MODEL_CODES[kind])
    rows = []
    if kind == "MLP":
        epochs = sorted(set(int(value) for value in CFG["mlp_epochs"]))
        if not epochs or epochs[0] < 1:
            raise ValueError("MLP epoch candidates must be positive integers.")
        location, scale = float(np.mean(yt)), max(float(np.std(yt)), 1e-12)
        model = make_model(kind, epochs[-1], seed, len(yt))
        scaled_y = (yt - location) / scale
        for epoch in range(1, epochs[-1] + 1):
            model.partial_fit(xt, scaled_y)
            if epoch in epochs:
                prediction = location + scale * model.predict(xv)
                rows.append({"model": kind, "seed": run_seed, "year": year,
                             "parameter": "epochs", "value": epoch,
                             "valid_mse": float(mean_squared_error(yv, prediction))})
    else:
        candidates = [0] if kind == "LR" else CFG["trees"]
        for parameter in candidates:
            model = fit_with_parameter(kind, xt, yt, parameter, seed)
            rows.append({"model": kind, "seed": run_seed, "year": year,
                         "parameter": "none" if kind == "LR" else "trees",
                         "value": int(parameter),
                         "valid_mse": float(mean_squared_error(yv, model.predict(xv)))})
    best = min(range(len(rows)), key=lambda i: rows[i]["valid_mse"])
    for i, row in enumerate(rows):
        row["selected"] = i == best
    return rows[best]["value"], rows

class GaussianCOLA:
    """Same ordered conditional increments; cache each prefix factorization."""

    def __init__(self, x_ref, model, seed):
        fit = LedoitWolf().fit(x_ref)
        self.mean, self.cov = np.asarray(fit.location_, float), np.asarray(fit.covariance_, float)
        self.model, self.k = model, x_ref.shape[1]
        rng = np.random.default_rng(seed)
        background = np.asarray(rng.multivariate_normal(self.mean, self.cov, CFG["base_draws"]), np.float32)
        self.base = float(np.mean(self.predict(background), dtype=np.float64))
        self.prefixes = []
        for size in range(1, self.k):
            cross = self.cov[:size, size:]
            gain = np.linalg.solve(self.cov[:size, :size], cross)
            covariance = self.cov[size:, size:] - cross.T @ gain
            values, vectors = np.linalg.eigh((covariance + covariance.T) / 2)
            root = vectors @ np.diag(np.sqrt(np.maximum(values, 0)))
            self.prefixes.append((size, gain, root))

    def predict(self, x):
        return np.asarray(self.model.predict(x), dtype=np.float64)

    def explain(self, x, seed):
        rng = np.random.default_rng(seed)
        attr = np.empty((len(x), self.k), dtype=np.float64)
        previous = np.full(len(x), self.base)
        draws_n = int(CFG["ce_draws"])
        if draws_n < 2 or draws_n % 2:
            raise ValueError("ce_draws must be an even integer >= 2 for antithetic integration.")
        for size, gain, root in self.prefixes:
            z = rng.standard_normal((draws_n // 2, self.k - size))
            z = np.concatenate([z, -z], axis=0) @ root.T
            current = np.empty(len(x), dtype=np.float64)
            for start in range(0, len(x), CFG["ce_batch"]):
                stop = min(start + CFG["ce_batch"], len(x))
                xb = x[start:stop]
                center = self.mean[size:] + (xb[:, :size] - self.mean[:size]) @ gain
                filled = np.broadcast_to(xb[:, None, :], (len(xb), draws_n, self.k)).copy()
                filled[:, :, size:] = center[:, None, :] + z[None, :, :]
                current[start:stop] = self.predict(filled.reshape(-1, self.k)).reshape(len(xb), draws_n).mean(axis=1)
            attr[:, size - 1] = current - previous
            previous = current
        pred = self.predict(x)
        attr[:, -1] = pred - previous
        return attr, pred

def validation_sample(return_dates, valid_index):
    """Stratify the plotting-rank sample across initial validation months."""
    rng = np.random.default_rng(seed_for(CFG["seed"], 711))
    dates = return_dates[valid_index]
    months = dates.unique().sort_values()
    budget = min(int(CFG["importance_rows"]), len(valid_index))
    per_month, remainder = divmod(budget, len(months))
    picked = []
    for position, month in enumerate(months):
        eligible = valid_index[np.asarray(dates == month)]
        n = min(len(eligible), per_month + int(position < remainder))
        picked.extend(rng.choice(eligible, n, replace=False).tolist())
    return np.sort(picked)

