def bootstrap_empirical(results):
    """Joint time resamples across models/seeds; summarize each model separately."""
    fidelity = pd.concat([r["fidelity"] for r in results], ignore_index=True)
    monthly = pd.concat([r["monthly"] for r in results], ignore_index=True)
    coefs = pd.concat([r["coefs"] for r in results], ignore_index=True)
    seed_ids = sorted(CFG["seeds"])
    available = fidelity.groupby("date")[["model", "seed", "method"]].apply(
        lambda b: b.drop_duplicates().shape[0])
    expected = len(CFG["models"]) * len(seed_ids) * len(METHODS)
    months = longest_month_span(available[available == expected].index)
    if len(months) < BS["min_months"]:
        raise ValueError("Too few shared consecutive months for empirical bootstrap.")
    rng = np.random.default_rng(np.random.SeedSequence([CFG["seed"], 8900]))
    index, length = stationary_indices(len(months), BS["reps"], rng, BS["block"])
    sums = fidelity.groupby(["model", "seed", "method", "date"])[
        ["err", "ref", "prefix_err", "prefix_ref"]].sum()
    kap = monthly.set_index(["model", "seed", "method", "date"])["kappa"]
    rows, distributions = [], []
    for kind in CFG["models"]:
        for method in METHODS:
            numerator = np.array([sums.loc[(kind, s, method)].reindex(months)["err"].to_numpy()
                                  for s in seed_ids])
            denominator = np.array([sums.loc[(kind, s, method)].reindex(months)["ref"].to_numpy()
                                    for s in seed_ids])
            prefix_numerator = np.array([
                sums.loc[(kind, s, method)].reindex(months)["prefix_err"].to_numpy()
                for s in seed_ids])
            prefix_denominator = np.array([
                sums.loc[(kind, s, method)].reindex(months)["prefix_ref"].to_numpy()
                for s in seed_ids])
            condition = np.array([kap.loc[(kind, s, method)].reindex(months).to_numpy()
                                  for s in seed_ids])
            # One set of month indices pairs every model/seed/method comparison.
            fid_draws = (numerator[:, index].sum(axis=2)
                         / denominator[:, index].sum(axis=2)).mean(axis=0)
            prefix_draws = (prefix_numerator[:, index].sum(axis=2)
                            / prefix_denominator[:, index].sum(axis=2)).mean(axis=0)
            kap_draws = np.median(condition[:, index], axis=2).mean(axis=0)
            fid_point = (numerator.sum(axis=1) / denominator.sum(axis=1)).mean()
            prefix_point = (prefix_numerator.sum(axis=1)
                            / prefix_denominator.sum(axis=1)).mean()
            kap_point = np.median(condition, axis=1).mean()
            for metric, point, sampled in [("infid", fid_point, fid_draws),
                                            ("prefix_infid", prefix_point, prefix_draws),
                                            ("kappa", kap_point, kap_draws)]:
                lo, hi = percentile_bounds(sampled)
                rows.append({"model": kind, "method": method, "metric": metric, "mean": point,
                             "lo": lo, "hi": hi, "boot": BS["reps"], "block": length,
                             "months": len(months), "seeds": len(seed_ids),
                             "unit": "Month", "scope": "Frozen models"})
                if BS["save_draws"]:
                    distributions.append(pd.DataFrame({"model": kind, "method": method,
                                                        "metric": metric,
                                                        "rep": np.arange(BS["reps"]),
                                                        "value": sampled}))
    save_csv(pd.DataFrame(rows), "appendix_real_boot_by_model")
    if distributions:
        save_csv(pd.concat(distributions, ignore_index=True), "real_boot_draws")
    if coefs.empty:
        save_csv(pd.DataFrame([{"status": "No full-rank months"}]), "real_fmb_status")
        return
    features = sorted(coefs["feature"].unique())
    wide = coefs.pivot(index="date", columns=["model", "seed", "method", "feature"], values="coef")
    required = pd.MultiIndex.from_product([CFG["models"], seed_ids, METHODS, features],
                                          names=["model", "seed", "method", "feature"])
    wide = wide.reindex(columns=required).dropna()
    fmb_months = longest_month_span(wide.index)
    if len(fmb_months) < BS["min_months"]:
        save_csv(pd.DataFrame([{"status": "Too few shared full-rank months",
                                "months": len(fmb_months)}]), "real_fmb_status")
        return
    wide = wide.reindex(fmb_months)
    fmb_rng = np.random.default_rng(np.random.SeedSequence([CFG["seed"], 8910]))
    fmb_index, fmb_length = stationary_indices(len(wide), BS["reps"], fmb_rng, BS["block"])
    fmb_rows, fmb_draws = [], []
    for kind in CFG["models"]:
        for method in METHODS:
            for feature in features:
                matrix = np.column_stack([wide[(kind, s, method, feature)].to_numpy()
                                          for s in seed_ids])
                # Average seeds within a prediction model before resampling months.
                series = matrix.mean(axis=1)
                boot = series[fmb_index].mean(axis=1)
                lo, hi = percentile_bounds(boot)
                fmb_rows.append({"model": kind, "method": method, "feature": feature,
                                 "mean": series.mean(), "boot_se": boot.std(ddof=1),
                                 "lo": lo, "hi": hi, "months": len(series),
                                 "seeds": len(seed_ids), "boot": BS["reps"],
                                 "block": fmb_length, "scope": "Frozen models"})
                if BS["save_draws"]:
                    fmb_draws.append(pd.DataFrame({"model": kind, "method": method,
                                                  "feature": feature,
                                                  "rep": np.arange(BS["reps"]), "value": boot}))
    save_csv(pd.DataFrame(fmb_rows), "appendix_real_fmb_boot_by_model")
    if fmb_draws:
        save_csv(pd.concat(fmb_draws, ignore_index=True), "real_fmb_boot_draws")
    save_csv(pd.DataFrame([{"status": "Complete", "months": len(wide),
                            "block": fmb_length, "start": fmb_months[0],
                            "end": fmb_months[-1], "models": len(CFG["models"])}]),
             "real_fmb_status")

