def parse_month(series, date_format=None):
    text = series.astype(str).str.replace(r"\.0$", "", regex=True)
    if date_format:
        parsed = pd.to_datetime(text, format=date_format, errors="raise")
    elif text.str.fullmatch(r"\d{6}").all():
        parsed = pd.to_datetime(text, format="%Y%m", errors="raise")
    else:
        parsed = pd.to_datetime(text, errors="raise")
    return parsed.dt.to_period("M")


def stable_cap(frame, cap, seed):
    if cap is None:
        return frame.copy()
    # Sampling depends on identifiers and month only, with a stable seed.
    return (frame.groupby("date", group_keys=False, sort=True)
            .apply(lambda block: block.sample(n=min(int(cap), len(block)),
                                              random_state=seed))
            .reset_index(drop=True))


def locate_real_panel():
    if not REAL["enabled"]:
        return None, "Disabled"
    path = Path(REAL["path"]).expanduser()
    if path.is_file():
        return path, "Local"
    if REAL["url"]:
        path.parent.mkdir(parents=True, exist_ok=True)
        log("Data", "Downloading the configured aligned panel.")
        urlretrieve(REAL["url"], path)
        return path, "URL"
    if REAL["upload"]:
        from google.colab import files
        log("Data", "Upload one aligned CSV or Parquet panel.")
        uploaded = files.upload()
        candidates = [name for name in uploaded
                      if Path(name).suffix.lower() in [".csv", ".parquet"]]
        if len(candidates) != 1:
            raise ValueError("Upload exactly one CSV or Parquet panel.")
        selected = BASE_DIR / Path(candidates[0]).name
        selected.write_bytes(uploaded[candidates[0]])
        return selected, "Upload"
    return None, "Missing input"


def load_real_panel(path):
    raw = pd.read_parquet(path) if path.suffix.lower() == ".parquet" else pd.read_csv(path)
    required = [REAL["id_col"], REAL["date_col"], REAL["target_col"]]
    missing = [name for name in required if name not in raw.columns]
    if missing:
        raise ValueError(f"Missing panel columns: {missing}")
    feature_names = REAL["features"]
    if feature_names is None:
        # Preserve the supplied schema order; use pre-test data for eligibility.
        feature_names = [name for name in raw.select_dtypes(include=np.number).columns
                         if name not in required]
    else:
        feature_names = list(feature_names)
    if not feature_names:
        raise ValueError("The panel needs numeric feature columns.")
    if set(feature_names) & set(required):
        raise ValueError("Feature columns must be distinct from id, date, and y.")
    feature_names = list(dict.fromkeys(feature_names))
    for name in feature_names:
        if name not in raw.columns:
            raise ValueError(f"Unknown feature: {name}")
    panel = raw[required + feature_names].copy()
    panel = panel.rename(columns={REAL["id_col"]: "id", REAL["date_col"]: "date",
                                   REAL["target_col"]: "y"})
    if panel[["id", "date"]].isna().any().any():
        raise ValueError("Panel identifiers and dates must be present.")
    panel["date"] = parse_month(panel["date"], REAL["date_format"])
    if panel.duplicated(["id", "date"]).any():
        raise ValueError("The panel contains duplicate id-month rows.")
    for name in ["y", *feature_names]:
        panel[name] = pd.to_numeric(panel[name], errors="raise")
    panel[["y", *feature_names]] = panel[["y", *feature_names]].replace(
        [np.inf, -np.inf], np.nan)
    panel = panel.dropna(subset=["y"]).sort_values(["date", "id"]).reset_index(drop=True)
    return panel, feature_names


def empirical_diagnostics(path, run_seed, kind, prepared=None):
    prefix = f"real_{kind}_s{run_seed}"
    panel, feature_names = load_real_panel(path) if prepared is None else prepared
    months = sorted(panel["date"].unique())
    purge = int(REAL["purge_months"])
    if REAL["train_end"] is not None or REAL["valid_end"] is not None:
        if REAL["train_end"] is None or REAL["valid_end"] is None:
            raise ValueError("Set both train_end and valid_end.")
        t_end = pd.Period(REAL["train_end"], freq="M")
        v_end = pd.Period(REAL["valid_end"], freq="M")
        tr_dates = [m for m in months if m <= t_end]
        va_dates = [m for m in months if t_end + purge < m <= v_end]
        te_dates = [m for m in months if m > v_end + purge]
    else:
        cut1 = int(len(months) * REAL["train_share"])
        cut2 = int(len(months) * (REAL["train_share"] + REAL["valid_share"]))
        tr_dates = months[:max(0, cut1 - purge)]
        va_dates = months[cut1:max(cut1, cut2 - purge)]
        te_dates = months[cut2:]
    if min(len(tr_dates), len(va_dates), len(te_dates)) < 3:
        raise ValueError("Each chronological split needs at least three months.")
    train = panel[panel["date"].isin(tr_dates)].copy()
    valid = panel[panel["date"].isin(va_dates)].copy()
    test = panel[panel["date"].isin(te_dates[:REAL["max_test_months"]])].copy()
    # Feature eligibility is determined exclusively from the training split.
    eligible = [name for name in feature_names
                if train[name].notna().sum() > 1
                and train[name].std(skipna=True) > 1e-12]
    selected = eligible[:int(REAL["max_features"])]
    if not 2 <= len(selected) <= 10:
        raise ValueError("The empirical benchmark requires 2 to 10 eligible features.")
    feature_map = pd.DataFrame({"Feature": [f"X{j + 1}" for j in range(len(selected))],
                                "Source": selected})
    save_csv(feature_map, f"{prefix}_features", show=False)
    log("Data", f"Empirical benchmark subset: {len(selected)} of {len(feature_names)} features.")
    train = stable_cap(train, REAL["max_train_per_month"], int(CFG["seed"] + 700))
    valid = stable_cap(valid, REAL["max_train_per_month"], int(CFG["seed"] + 701))
    test = stable_cap(test, REAL["max_test_per_month"], int(CFG["seed"] + 702))
    split_rows = []
