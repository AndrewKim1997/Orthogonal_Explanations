print("Estimating Table 5: Cox proportional-hazards models for drawdown events.")
survival_rows = []
for year in range(pd.Period(CFG["test_start"], freq="M").year, raw_end.year + 1):
    january = pd.Period(f"{year}-01", freq="M")
    january_rows = test.loc[test["return_date"] == january]
    for _, row in january_rows.iterrows():
        identifier = row["id"]
        wealth, peak, duration, event = 1.0, 1.0, 0, 0
        for offset in range(CFG["survival_horizon_months"]):
            month = january + offset
            if month > raw_end:
                break
            value = total_returns.loc[month, identifier]
            if not np.isfinite(value):
                break
            if value <= -1.0:
                raise RuntimeError("A portfolio return is at or below minus 100 percent.")
            duration = offset + 1
            wealth *= 1.0 + float(value)
            peak = max(peak, wealth)
            if 1.0 - wealth / peak >= CFG["drawdown_threshold"]:
                event = 1
                break
        if duration == 0:
            continue
        record = {"id": identifier, "cohort": year, "duration": duration, "event": event,
                  "baseline_information_date": str(row["information_date"]),
                  "baseline_return_date": str(january)}
        record.update({feature: float(row[f"Z_{feature}"]) for feature in FEATURES})
        survival_rows.append(record)
survival = pd.DataFrame(survival_rows)
if survival.empty:
    raise RuntimeError("The annual landmark sample is empty.")
survival.to_csv(OUT / "survival_data_all_cohorts.csv", index=False)
