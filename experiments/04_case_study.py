def download_source(url, filename):
    last_error = None
    for attempt in range(3):
        try:
            response = requests.get(url, timeout=(15, 90),
                                    headers={"User-Agent": "COLA-Case-Study/2.0"})
            response.raise_for_status()
            payload = response.content
            if not zipfile.is_zipfile(io.BytesIO(payload)):
                raise ValueError(f"Invalid source ZIP: {filename}")
            (RAW / filename).write_bytes(payload)
            SOURCES.append({"file": filename, "url": url, "bytes": len(payload),
                            "sha256": hashlib.sha256(payload).hexdigest()})
            return payload
        except Exception as exc:
            last_error = exc
            if attempt < 2:
                time.sleep(1 + attempt)
    raise RuntimeError(f"Source download failed: {filename}") from last_error


def read_french_monthly(payload, expected_columns, value_weighted=False):
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        names = [name for name in archive.namelist()
                 if name.lower().endswith(".csv") and "__MACOSX" not in name]
        if len(names) != 1:
            raise ValueError("The source ZIP must contain one CSV.")
        content = archive.read(names[0])
    try:
        text = content.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = content.decode("latin-1")
    armed, header, dates, values = not value_weighted, None, [], []
    for line in text.splitlines():
        title = re.sub(r"[-\s]+", " ", line.lower()).strip()
        if value_weighted and all(word in title for word in ("value", "weighted", "monthly")):
            armed = True
            continue
        if not armed:
            continue
        fields = [value.strip() for value in next(csv.reader([line]))] if line.strip() else []
        while len(fields) > expected_columns + 1 and fields[-1] == "":
            fields.pop()
        first = fields[0] if fields else ""
        if len(first) == 6 and first.isdigit():
            if header is None or len(fields) != expected_columns + 1:
                raise ValueError("Unexpected French monthly table schema.")
            dates.append(first)
            values.append([float(value) if value else np.nan for value in fields[1:]])
        elif dates:
            break
        elif len(fields) == expected_columns + 1 and first.lower() in ("", "date") and all(fields[1:]):
            header = fields[1:]
    if not dates or header is None or len(set(header)) != expected_columns:
        raise ValueError("The requested French monthly table was not found.")
    array = np.asarray(values, dtype=float)
    missing = (np.isclose(array, -99.99, rtol=0, atol=1e-8)
               | np.isclose(array, -999.0, rtol=0, atol=1e-8))
    array[missing] = np.nan
    index = pd.to_datetime(dates, format="%Y%m").to_period("M")
    if index.duplicated().any():
        raise ValueError("Duplicate source months.")
    return pd.DataFrame(array / 100.0, index=index, columns=header).sort_index()


def require_full_rank(design, context):
    design = np.asarray(design, dtype=float)
    if design.ndim != 2 or not np.isfinite(design).all():
        raise RuntimeError(f"{context}: the design contains nonfinite entries.")
    singular = np.linalg.svd(design, compute_uv=False)
    if (design.shape[0] <= design.shape[1] or not len(singular)
            or singular[-1] <= CFG["rank_tolerance"] * singular[0]):
        raise RuntimeError(f"{context}: the specified coefficient vector is not identified.")


def check_estimate(row, context):
    columns = ["coef", "se", "statistic", "pvalue", "lower", "upper"]
    if not np.isfinite([row[column] for column in columns]).all() or row["se"] <= 0:
        raise RuntimeError(f"{context}: estimation did not produce finite uncertainty estimates.")
    return row


def term_label(name):
    if name == "const":
        return "Intercept"
    return name[2:] if name.startswith("Z_") else name


def number(value, digits=3):
    if not np.isfinite(float(value)):
        raise RuntimeError("A nonfinite estimate reached table rendering.")
    return f"{float(value):.{digits}f}"


def pvalue(value):
    return "<0.001" if float(value) < 0.001 else number(value, 3)


def regression_display(results, group=None, statistic="t"):
    rows = []
    for _, result in results.iterrows():
        row = {}
        if group is not None:
            row[group] = str(result[group])
        row.update({"Term": term_label(result["term"]),
                    "Coef.": number(result["coef"]), "Std. err.": number(result["se"]),
                    statistic: number(result["statistic"]), f"P>|{statistic}|": pvalue(result["pvalue"]),
                    "2.5%": number(result["lower"]), "97.5%": number(result["upper"])})
        rows.append(row)
    return pd.DataFrame(rows)


def latex_escape(value):
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
                    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
                    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
                    "<": r"\textless{}", ">": r"\textgreater{}"}
    return "".join(replacements.get(char, char) for char in str(value))


def add_table(frame, title, stem, notes, footer, group=None):
    # Display strings are separate from the numerical estimates saved to CSV.
    formatted = frame.copy()
    if group is not None:
        labels = formatted[group].copy()
        formatted.loc[labels.eq(labels.shift()), group] = ""
    rows = []
    for index, (_, row) in enumerate(formatted.iterrows()):
        boundary = (group is not None and index > 0
                    and frame.iloc[index][group] != frame.iloc[index - 1][group])
        class_name = ' class="group-start"' if boundary else ""
        cells = "".join(f"<td>{html.escape(str(value))}</td>" for value in row)
        rows.append(f"<tr{class_name}>{cells}</tr>")
    header = "".join(f"<th>{html.escape(str(column))}</th>" for column in frame.columns)
    footer_html = "".join(
        f'<tr><th colspan="{len(frame.columns) - 1}">{html.escape(str(label))}</th>'
        f"<td>{html.escape(str(value))}</td></tr>" for label, value in footer
    )
    document = (
        '<div class="cola-box">'
        f"<h3>{html.escape(title)}</h3>"
        f'<table class="cola-table"><thead><tr>{header}</tr></thead>'
        f"<tbody>{''.join(rows)}</tbody><tfoot>{footer_html}</tfoot></table>"
        f'<p class="cola-note">{html.escape(notes)}</p></div>'
    )
    display(HTML(document))
    (OUT / f"{stem}.html").write_text(document, encoding="utf-8")
    frame.to_csv(OUT / f"{stem}_display.csv", index=False)
    lines = [
        r"\begin{table}[t]", r"\centering",
        r"\caption{" + latex_escape(title.split(". ", 1)[-1]) + "}",
        r"\label{tab:" + stem + "}", r"\scriptsize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{" + "l" * (2 if group is not None else 1)
        + "r" * (len(frame.columns) - (2 if group is not None else 1)) + "}",
        r"\toprule",
        " & ".join(latex_escape(column) for column in frame.columns) + r" \\",
        r"\midrule",
    ]
    for index, (_, row) in enumerate(formatted.iterrows()):
        if (group is not None and index > 0
                and frame.iloc[index][group] != frame.iloc[index - 1][group]):
            lines.append(r"\midrule")
        lines.append(" & ".join(latex_escape(value) for value in row) + r" \\")
    lines.append(r"\midrule")
    for label, value in footer:
        lines.append(r"\multicolumn{" + str(len(frame.columns) - 1) + "}{l}{"
                     + latex_escape(label) + "} & " + latex_escape(value) + r" \\")
    lines += [
        r"\bottomrule", r"\end{tabular}", r"\par\smallskip",
        r"\begin{minipage}{\linewidth}\scriptsize " + latex_escape(notes) + r"\end{minipage}",
        r"\end{table}",
    ]
    (OUT / f"{stem}.tex").write_text("\n".join(lines), encoding="utf-8")
    TABLES.append({"title": title, "stem": stem, "notes": notes,
                   "footer": footer, "html": document})


