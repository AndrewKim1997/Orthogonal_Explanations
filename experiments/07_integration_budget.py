def make_sim_panel(rho, run_seed):
    rng = np.random.default_rng(seed_for(run_seed, 100))
    nt = CFG["train_months"] + CFG["valid_months"] + CFG["test_months"]
    covariance = (1 - rho) * np.eye(CFG["k"]) + rho * np.ones((CFG["k"], CFG["k"]))
    innovations = rng.standard_normal((nt, CFG["n_assets"], CFG["k"])) @ np.linalg.cholesky(covariance).T
    x = np.empty_like(innovations)
    x[0] = innovations[0]
    for month in range(1, nt):
        x[month] = CFG["x_ar"] * x[month - 1] + np.sqrt(1 - CFG["x_ar"] ** 2) * innovations[month]
    flat = x.reshape(-1, CFG["k"])
    coefficient = np.array([0.7, -0.5, 0.35, 0.2, -0.15, 0.1])
    signal = flat @ coefficient + 0.45 * np.sin(flat[:, 0]) + 0.3 * (flat[:, 2] ** 2 - 1) + 0.35 * flat[:, 3] * flat[:, 4]
    response = signal + rng.standard_normal(len(flat)) * CFG["train_noise"] * (0.7 + 0.3 * np.abs(flat[:, 0]))
    dates = np.repeat(np.arange(nt), CFG["n_assets"])
    return flat, response, dates, covariance



def balanced_diagnostic_rows(dates, requested, seed):
    """Allocate a fixed observation budget across the complete test calendar."""
    dates = np.asarray(dates).astype(str)
    months = np.unique(dates)
    requested = min(int(requested), len(dates))
    rng = np.random.default_rng(seed)
    if requested < len(months):
        month_positions = np.rint(np.linspace(0, len(months) - 1, requested)).astype(int)
        selected = [int(rng.choice(np.flatnonzero(dates == months[i]))) for i in month_positions]
    else:
        counts = np.full(len(months), requested // len(months), int)
        counts[:requested % len(months)] += 1
        selected = []
        for month, count in zip(months, counts):
            available = np.flatnonzero(dates == month)
            selected.extend(rng.choice(available, min(int(count), len(available)), replace=False).tolist())
        if len(selected) < requested:
            remaining = np.setdiff1d(np.arange(len(dates)), selected)
            selected.extend(rng.choice(remaining, requested - len(selected), replace=False).tolist())
    return np.sort(np.asarray(selected, int))


def diagnostic_loss(values, reference):
    # Interior prefixes isolate conditional integration at the fixed baseline.
    error = values[:, 1:-1] - reference[:, 1:-1]
    delta = reference[:, -1, None] - reference[:, 1:-1]
    attribution, target = np.diff(values, axis=1), np.diff(reference, axis=1)
    error_sum = float(np.square(error).sum())
    delta_sum = float(np.square(delta).sum())
    attribution_error = float(np.square(attribution - target).sum())
    attribution_energy = float(np.square(target).sum())
    return {"rows": len(values), "prefix_cells": int(error.size),
        "prefix_squared_error_sum": error_sum, "reference_delta_squared_sum": delta_sum,
        "attribution_squared_error_sum": attribution_error,
        "reference_attribution_squared_sum": attribution_energy,
        "prefix_infid": error_sum / delta_sum if delta_sum > 1e-16 else np.nan,
        "prefix_rmse": float(np.sqrt(error_sum / error.size)) if error.size else np.nan,
        "attribution_nrmse": float(np.sqrt(attribution_error / attribution_energy))
                              if attribution_energy > 1e-16 else np.nan}


def integration_diagnostic(geometry, predictor, baseline, x, stream, reference_stream, repeat_stream):
    """Use independent reference draws and three paired integration repetitions."""
    estimated = BudgetGaussianCOLA(geometry, predictor, baseline)
    reference_explainer = BudgetGaussianCOLA(geometry, predictor, baseline, analytical=predictor.kind == "LR")
    tick = time.perf_counter()
    reference_values = reference_explainer.values(x, CFG["diagnostic_reference_draws"],
                                                 reference_stream, "Antithetic")
    timing = [{"stage": "Diagnostic reference", "sampler": "Analytical" if predictor.kind == "LR" else "Antithetic",
        "draws": 0 if predictor.kind == "LR" else CFG["diagnostic_reference_draws"],
        "repeat": None, "rows": len(x), "elapsed_seconds": time.perf_counter() - tick,
        "conditional_prediction_rows": 0 if predictor.kind == "LR" else len(x) * (len(FEATURES) - 1) * CFG["diagnostic_reference_draws"]}]
    rows, all_values = [], []
    for repeat in range(CFG["diagnostic_repetitions"]):
        current_stream = stream if repeat == 0 else seed_for(repeat_stream, repeat)
        repeated_values = []
        for sampler in SAMPLERS:
            tick = time.perf_counter()
            values = estimated.multi_values(x, CFG["diagnostic_budgets"], current_stream, sampler)
            timing.append({"stage": "Diagnostic nested estimates", "sampler": sampler,
                "draws": max(CFG["diagnostic_budgets"]), "repeat": repeat, "rows": len(x),
                "elapsed_seconds": time.perf_counter() - tick,
                "conditional_prediction_rows": len(x) * (len(FEATURES) - 1) * max(CFG["diagnostic_budgets"])})
            for budget in CFG["diagnostic_budgets"]:
                rows.append({"sampler": sampler, "draws": budget, "repeat": repeat,
                             **diagnostic_loss(values[budget], reference_values)})
            repeated_values.append(np.stack([values[budget] for budget in CFG["diagnostic_budgets"]]))
        all_values.append(np.stack(repeated_values))
    return rows, timing, reference_values, np.stack(all_values)


def comparison_with_main(attribution, main):
    output = []
    for j in range(attribution.shape[1]):
        current, baseline = attribution[:, j], main[:, j]
        baseline_sd, current_sd = float(baseline.std()), float(current.std())
        output.append({"feature_index_one_based": j + 1,
            "correlation_with_main": float(np.corrcoef(current, baseline)[0, 1])
                if min(baseline_sd, current_sd) > 1e-12 else np.nan,
            "nrmse_from_main": float(np.sqrt(np.mean((current - baseline) ** 2))) / baseline_sd
                if baseline_sd > 1e-12 else np.nan})
    return output



