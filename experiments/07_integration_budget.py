def pool_diagnostic(frame, keys):
    totals = ["rows", "prefix_cells", "prefix_squared_error_sum", "reference_delta_squared_sum",
              "attribution_squared_error_sum", "reference_attribution_squared_sum"]
    pooled = frame.groupby(keys, as_index=False)[totals].sum()
    pooled["prefix_infid"] = pooled["prefix_squared_error_sum"] / pooled["reference_delta_squared_sum"].where(
        pooled["reference_delta_squared_sum"] > 1e-16)
    pooled["prefix_rmse"] = np.sqrt(pooled["prefix_squared_error_sum"] / pooled["prefix_cells"])
    pooled["attribution_nrmse"] = np.sqrt(pooled["attribution_squared_error_sum"] / pooled["reference_attribution_squared_sum"].where(
        pooled["reference_attribution_squared_sum"] > 1e-16))
    return pooled


