"""Regenerate independent experiment scripts from the archived Colab export."""

import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "archive" / "orthogonal_explanations.py"
SOURCE_SHA256 = "f0dda01b4ce8c3d2e9311705895c8982cdd619d81cc596260c383868738f55a5"
# Inclusive, 1-based ranges in the byte-preserved source.
SECTIONS = [
    ("01_explanation_quality.py", "Experiment 1: explanation quality and shared-response inference", 12, 1918),
    ("02_financial_associations.py", "Experiment 2: financial associations in French 100", 1922, 3519),
    ("03_cross_dataset_compatibility.py", "Experiment 3: cross-dataset and cross-model compatibility", 3523, 6146),
    ("04_case_study.py", "Case study: five analyses of one frozen OLS explanation panel", 6150, 6916),
    ("05_conditional_reference.py", "Appendix C.1: conditional reference ablation", 6920, 8401),
    ("06_feature_order.py", "Appendix C.2: feature-order sensitivity", 8405, 10048),
    ("07_integration_budget.py", "Appendix C.3: integration budget and sampling", 10052, 11777),
    ("08_downstream_specifications.py", "Appendix C.4: downstream specification robustness", 11781, 13704),
]


def generated_files():
    payload = SOURCE.read_bytes()
    actual = hashlib.sha256(payload).hexdigest()
    if actual != SOURCE_SHA256:
        raise ValueError(f"Archived source hash mismatch: {actual}")
    lines = payload.decode("utf-8").splitlines(keepends=True)
    files, entries = {}, []
    for filename, title, first, last in SECTIONS:
        section = "".join(lines[first - 1:last])
        # Keep the complete scientific body, replacing notebook-only setup with
        # the repository's explicit dependency installation instructions.
        if filename == "04_case_study.py":
            body = section[section.index("import csv\n"):]
        else:
            body = section[section.index("# %% Cell 2: Imports\n"):]
        header = (
            '# -*- coding: utf-8 -*-\n'
            f'"""{title}.\n\n'
            'Generated by tools/extract_experiments.py.\n'
            f'Source: archive/orthogonal_explanations.py, lines {first}-{last}.\n'
            'Install once with: python -m pip install -e ".[experiments]"\n'
            'Run this file independently from the repository root.\n'
            '"""\n\n'
        )
        content = header + body.rstrip() + "\n"
        ast.parse(content, filename=filename)
        relative = f"experiments/{filename}"
        files[relative] = content
        entries.append({
            "path": relative, "title": title, "source_lines": [first, last],
            "sha256": hashlib.sha256(content.encode()).hexdigest(),
        })
    files["archive/manifest.json"] = json.dumps({
        "source": "archive/orthogonal_explanations.py",
        "source_sha256": SOURCE_SHA256,
        "transformation": "Replace notebook headers and dependency-installation cells; retain each scientific body verbatim.",
        "experiments": entries,
    }, indent=2) + "\n"
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check tracked files without writing them.")
    args = parser.parse_args()
    mismatches = []
    for relative, content in generated_files().items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_bytes() != content.encode():
                mismatches.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode())
    if mismatches:
        raise SystemExit("Regeneration required: " + ", ".join(mismatches))
    print(f"{'Checked' if args.check else 'Generated'} {len(SECTIONS)} independent experiments and their manifest.")


if __name__ == "__main__":
    main()
