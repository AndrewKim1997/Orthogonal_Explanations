class ReturnPredictor:
    """Predict in unscaled monthly-return units for every model family."""

    def __init__(self, estimator, kind, location, scale):
        self.estimator, self.kind = estimator, kind
        self.location, self.scale = float(location), float(scale)

    def predict(self, x):
        x = np.ascontiguousarray(x, dtype=np.float32)
        if self.kind == "XGB":
            value = self.estimator.get_booster().inplace_predict(x, validate_features=False)
        else:
            value = self.estimator.predict(x)
        return np.asarray(value, float) * self.scale + self.location

    def linear_parameters(self):
        return (np.asarray(self.estimator.coef_, float) * self.scale,
                float(self.estimator.intercept_) * self.scale + self.location)


def fit_preprocessor(x, seed):
    if not np.isfinite(x).all():
        raise ValueError("Model input must have a complete observed feature history.")
    transform = QuantileTransformer(n_quantiles=min(1000, len(x)), output_distribution="normal",
        subsample=min(CFG["quantile_subsample"], len(x)), random_state=seed)
    return transform, np.asarray(transform.fit_transform(x), np.float32)


def prepare_fold(dataset, panel, year):
    path = MODEL_DIR / dataset / f"preprocessing_{year}.joblib"
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file():
        fold = joblib.load(path)
        if fold["signature"] != DATA_SIGNATURE:
            raise ValueError("Preprocessing checkpoint belongs to different source data.")
        return fold
    train, valid, pretest, test = annual_split(panel, year, dataset=dataset)
    x = panel[FEATURES].to_numpy(np.float32)
    code = DATASETS.index(dataset)
    initial, _ = fit_preprocessor(x[train], seed_for(41, code, year))
    final, _ = fit_preprocessor(x[pretest], seed_for(42, code, year))
    fold = {"signature": DATA_SIGNATURE, "train": train, "valid": valid, "pretest": pretest,
            "test": test, "initial": initial, "final": final}
    joblib.dump(fold, path, compress=3)
    return fold


def new_estimator(kind, parameter, seed):
    if kind == "LR":
        return LinearRegression()
    if kind == "XGB":
        return XGBRegressor(n_estimators=int(parameter), max_depth=CFG["xgb_depth"],
            learning_rate=CFG["xgb_learning_rate"], objective="reg:squarederror", tree_method="hist",
            device="cpu", subsample=0.8, colsample_bytree=0.9, reg_lambda=1.0,
            n_jobs=CFG["n_jobs"], random_state=seed)
    if kind == "MLP":
        return MLPRegressor(hidden_layer_sizes=CFG["mlp_hidden"], activation="relu", solver="adam",
            alpha=CFG["mlp_alpha"], batch_size=CFG["mlp_batch_size"],
            learning_rate_init=CFG["mlp_learning_rate"], max_iter=1, early_stopping=False,
            shuffle=True, random_state=seed)
    raise ValueError(f"Unknown model: {kind}")


def fit_mlp_epochs(estimator, x, y, epochs):
    with warnings.catch_warnings(), threadpool_limits(limits=CFG["n_jobs"]):
        warnings.simplefilter("ignore", ConvergenceWarning)
        for _ in range(int(epochs)):
            estimator.partial_fit(x, y)
    return estimator


def tune_and_refit(kind, x, y, fold, run_seed, dataset, year):
    train, valid, pretest = [fold[key] for key in ["train", "valid", "pretest"]]
    xt, xv = [np.asarray(fold["initial"].transform(x[index]), np.float32) for index in [train, valid]]
    yt, yv = y[train], y[valid]
    location, scale = float(yt.mean()), max(float(yt.std()), 1e-6)
    normalized_y = (yt - location) / scale
    seed = seed_for(51, DATASETS.index(dataset), CFG["models"].index(kind), year, run_seed)
    rows = []
    if kind == "LR":
        selected = None
        estimator = new_estimator(kind, selected, seed)
        design = np.column_stack([np.ones(len(xt)), xt])
        singular = np.linalg.svd(design, compute_uv=False)
        if singular[-1] <= CFG["rank_tol"] * singular[0]:
            raise ValueError(f"OLS training design is rank deficient: {dataset}, {year}")
        with threadpool_limits(limits=CFG["n_jobs"]):
            estimator.fit(xt, normalized_y)
        loss = mean_squared_error(yv, ReturnPredictor(estimator, kind, location, scale).predict(xv))
        rows.append({"parameter": "OLS", "valid_mse": float(loss)})
    elif kind == "XGB":
        best_loss, selected = np.inf, None
        for trees in CFG["xgb_trees"]:
            estimator = new_estimator(kind, trees, seed)
            estimator.fit(xt, normalized_y)
            loss = float(mean_squared_error(yv, ReturnPredictor(estimator, kind, location, scale).predict(xv)))
            rows.append({"parameter": trees, "valid_mse": loss})
            if loss < best_loss:
                best_loss, selected = loss, trees
    else:
        best_loss, selected = np.inf, None
        estimator = new_estimator(kind, None, seed)
        for epoch in range(1, max(CFG["mlp_epochs"]) + 1):
            fit_mlp_epochs(estimator, xt, normalized_y, 1)
            if epoch in CFG["mlp_epochs"]:
                loss = float(mean_squared_error(yv, ReturnPredictor(estimator, kind, location, scale).predict(xv)))
                rows.append({"parameter": epoch, "valid_mse": loss})
                if loss < best_loss:
                    best_loss, selected = loss, epoch
    xf = np.asarray(fold["final"].transform(x[pretest]), np.float32)
    yf = y[pretest]
    location, scale = float(yf.mean()), max(float(yf.std()), 1e-6)
    estimator = new_estimator(kind, selected, seed)
    if kind == "MLP":
        fit_mlp_epochs(estimator, xf, (yf - location) / scale, selected)
    else:
        with threadpool_limits(limits=CFG["n_jobs"]):
            estimator.fit(xf, (yf - location) / scale)
    predictor = ReturnPredictor(estimator, kind, location, scale)
    if not np.isfinite(predictor.predict(xf[:min(32, len(xf))])).all():
        raise FloatingPointError(f"Nonfinite fitted predictions: {dataset}, {kind}, {year}")
    for row in rows:
        row.update({"dataset": dataset, "model": kind, "seed": run_seed, "year": year,
                    "selected": row["parameter"] == ("OLS" if kind == "LR" else selected)})
    return predictor, xf, selected, rows

# %% Cell 6: Ordered COLA with a common feature order
class GaussianCOLA:
    """Ordered conditional increments under a fitted Gaussian reference.

    Gaussian conditional expectations are analytic for OLS. Tree and neural
    models use the same antithetic integration budget and feature order.
    The telescoping sum equals prediction minus the stored reference baseline.
    """

    def __init__(self, x_reference, predictor, seed):
        self.predictor, self.k = predictor, x_reference.shape[1]
        fit = LedoitWolf().fit(x_reference)
        self.mean = np.asarray(fit.location_, float)
        self.cov = np.asarray(fit.covariance_, float)
        self.prefixes = []
        for size in range(1, self.k):
            cross = self.cov[:size, size:]
            gain = np.linalg.solve(self.cov[:size, :size], cross)
            conditional_cov = self.cov[size:, size:] - cross.T @ gain
            eigenvalues, eigenvectors = np.linalg.eigh((conditional_cov + conditional_cov.T) / 2)
            root = eigenvectors @ np.diag(np.sqrt(np.maximum(eigenvalues, 0)))
            self.prefixes.append((size, gain, root))
        if predictor.kind == "LR":
            self.weight, self.intercept = predictor.linear_parameters()
            self.base = float(self.intercept + self.mean @ self.weight)
        else:
            rng = np.random.default_rng(seed)
            background = rng.multivariate_normal(self.mean, self.cov, CFG["base_draws"])
            self.base = float(predictor.predict(background).mean())

    def explain(self, x, seed):
        x = np.asarray(x, np.float32)
        attr = np.empty((len(x), self.k), float)
        previous = np.full(len(x), self.base)
        rng = np.random.default_rng(seed)
        draws = int(CFG["ce_draws"])
        if draws < 2 or draws % 2:
            raise ValueError("ce_draws must be an even integer >= 2.")
        for size, gain, root in self.prefixes:
            center = self.mean[size:] + (x[:, :size] - self.mean[:size]) @ gain
            if self.predictor.kind == "LR":
                current = self.intercept + x[:, :size] @ self.weight[:size] + center @ self.weight[size:]
            else:
                z = rng.standard_normal((draws // 2, self.k - size))
                z = np.concatenate([z, -z], axis=0) @ root.T
                current = np.empty(len(x))
                for start in range(0, len(x), CFG["ce_batch"]):
                    stop = min(len(x), start + CFG["ce_batch"])
                    filled = np.broadcast_to(x[start:stop, None, :], (stop - start, draws, self.k)).copy()
                    filled[:, :, size:] = center[start:stop, None, :] + z[None, :, :]
                    current[start:stop] = self.predictor.predict(filled.reshape(-1, self.k)).reshape(-1, draws).mean(axis=1)
            attr[:, size - 1] = current - previous
            previous = current
        prediction = self.predictor.predict(x)
        attr[:, -1] = prediction - previous
        return attr, prediction


