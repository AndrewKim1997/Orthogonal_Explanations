# %% Cell 5: Conditional reference and local explanations
class GaussianReference:
    """A pre-test Gaussian reference with shrinkage covariance."""

    def __init__(self, x_ref, predict, seed):
        self.predict = predict
        self.k = x_ref.shape[1]
        fitted = LedoitWolf().fit(x_ref)
        self.mean = fitted.location_.copy()
        self.cov = fitted.covariance_.copy()
        self.cache = {}
        rng = np.random.default_rng(seed)
        draws = rng.multivariate_normal(self.mean, self.cov, CFG["base_draws"])
        self.base = float(np.mean(predict(draws)))

    def conditional_params(self, mask):
        if mask in self.cache:
            return self.cache[mask]
        obs = np.array([j for j in range(self.k) if mask & (1 << j)], dtype=int)
        miss = np.array([j for j in range(self.k) if not mask & (1 << j)], dtype=int)
        if len(obs):
            oo = self.cov[np.ix_(obs, obs)]
            om = self.cov[np.ix_(obs, miss)]
            gain = np.linalg.solve(oo, om)
            cond_cov = self.cov[np.ix_(miss, miss)] - om.T @ gain
        else:
            gain = np.zeros((0, len(miss)))
            cond_cov = self.cov[np.ix_(miss, miss)]
        cond_cov = (cond_cov + cond_cov.T) / 2
        eigval, eigvec = np.linalg.eigh(cond_cov)
        root = eigvec @ np.diag(np.sqrt(np.maximum(eigval, 0.0)))
        self.cache[mask] = obs, miss, gain, root
        return self.cache[mask]

    def values(self, x, draws, seed, label="CE"):
        """Enumerate coalitions; approximate their conditional expectations."""
        k = self.k
        if k > 10:
            raise ValueError("Exact coalition enumeration requires K <= 10.")
        values = np.empty((len(x), 1 << k), dtype=float)
        values[:, 0] = self.base
        values[:, -1] = self.predict(x)
        rng = np.random.default_rng(seed)
        for mask in tqdm(range(1, (1 << k) - 1), desc=label, leave=False):
            obs, miss, gain, root = self.conditional_params(mask)
            half = (draws + 1) // 2
            z = rng.standard_normal((half, len(miss)))
            z = np.concatenate([z, -z], axis=0)[:draws] @ root.T
            for start in range(0, len(x), CFG["ce_batch"]):
                stop = min(start + CFG["ce_batch"], len(x))
                xb = x[start:stop]
                center = self.mean[miss] + (xb[:, obs] - self.mean[obs]) @ gain
                filled = np.broadcast_to(xb[:, None, :],
                                         (len(xb), draws, k)).copy()
                filled[:, :, miss] = center[:, None, :] + z[None, :, :]
                values[start:stop, mask] = self.predict(
                    filled.reshape(-1, k)).reshape(len(xb), draws).mean(axis=1)
        return values


def conditional_shap(values, k):
    """Exact Shapley coalition weights applied to estimated coalition values."""
    attr = np.zeros((len(values), k))
    for j in range(k):
        for mask in range(1 << k):
            if mask & (1 << j):
                continue
            size = int(mask).bit_count()
            weight = 1.0 / (k * math.comb(k - 1, size))
            attr[:, j] += weight * (values[:, mask | (1 << j)] - values[:, mask])
    return attr


def ordered_cola(values, k, order=None):
    order = list(range(k)) if order is None else list(order)
    attr = np.zeros((len(values), k))
    prefix = 0
    for j in order:
        nxt = prefix | (1 << j)
        attr[:, j] = values[:, nxt] - values[:, prefix]
        prefix = nxt
    return attr


def local_lime(x_ref, x, predict, seed, names):
    """Convert continuous LIME slopes to feature contributions in output units."""
    explainer = LimeTabularExplainer(
        x_ref, mode="regression", feature_names=names,
        discretize_continuous=False, feature_selection="none",
        sample_around_instance=True, random_state=seed,
    )
    attr = np.zeros_like(x, dtype=float)
    base = np.empty(len(x), dtype=float)
    score = np.empty(len(x), dtype=float)
    for i in tqdm(range(len(x)), desc="LIME", leave=False):
        explanation = explainer.explain_instance(
            x[i], predict, num_features=x.shape[1],
            num_samples=CFG["lime_samples"],
            model_regressor=Ridge(alpha=CFG["lime_ridge"]),
        )
        weights = np.zeros(x.shape[1])
        for feature, weight in explanation.local_exp[1]:
            weights[feature] = weight
        scaled = (x[i] - explainer.scaler.mean_) / explainer.scaler.scale_
        attr[i] = weights * scaled
        base[i] = float(explanation.intercept[1])
        raw_score = explanation.score
        score[i] = float(raw_score[0] if isinstance(raw_score, dict) else raw_score)
    return attr, base, score


def explain_all(x_ref, x, model, seed, names):
    started = time.perf_counter()
    predict = lambda arr: np.asarray(model.predict(arr), dtype=float)
    reference = GaussianReference(x_ref, predict, seed)
    values = reference.values(x, CFG["ce_draws"], seed + 1, "Attribution CE")
    common_base = np.full(len(x), reference.base)
    attrs = {"SHAP": conditional_shap(values, x.shape[1]),
             "COLA": ordered_cola(values, x.shape[1])}
    bases = {"SHAP": common_base.copy(), "COLA": common_base.copy()}
    pred = predict(x)
    ablation = np.empty_like(x)
    for j in range(x.shape[1]):
        replaced = x.copy()
        replaced[:, j] = x_ref[:, j].mean()
        ablation[:, j] = pred - predict(replaced)
    attrs["Ablation"] = ablation
    bases["Ablation"] = np.full(len(x), float(predict(x_ref.mean(axis=0)[None])[0]))
    attrs["LIME"], bases["LIME"], lime_score = local_lime(
        x_ref, x, predict, seed + 2, names)
    log("XAI", f"Rows={len(x)}, K={x.shape[1]}, "
        f"time={time.perf_counter() - started:.1f}s")
    return attrs, bases, reference, pred, lime_score

# %% Cell 6: Explanation diagnostics
def condition_number(a):
    centered = a - a.mean(axis=0)
    scale = centered.std(axis=0, ddof=0)
    if len(a) <= a.shape[1] or np.any(scale <= 1e-12):
        return np.inf
    z = centered / scale
    s = np.linalg.svd(z, compute_uv=False)
    if s[-1] <= CFG["rank_tol"] * s[0]:
        return np.inf
    return float(s[0] / s[-1])


def diagnose_explanations(attrs, bases, reference, x, pred, dates, seed, tag):
    rng = np.random.default_rng(seed)
    # Cover every month; preserve whole cross-sections during later resampling.
    month_ids = np.unique(dates)
    per_month = max(1, CFG["fidelity_rows"] // len(month_ids))
    selected = np.sort(np.concatenate([
        rng.choice(np.flatnonzero(dates == month),
                   min(per_month, int(np.sum(dates == month))), replace=False)
        for month in month_ids
    ]))
    # Independent conditional draws keep evaluation separate from attribution.
    v_eval = reference.values(x[selected], CFG["eval_draws"], seed + 1,
                             "Held-out CE")
    k = x.shape[1]
    masks = np.arange(1, (1 << k) - 1)
    removed = 1.0 - ((masks[:, None] >> np.arange(k)) & 1)
    delta = pred[selected, None] - v_eval[:, masks]
    denominator = float(np.mean(delta ** 2))
    if denominator <= 1e-16:
        raise ValueError("The model has insufficient output variation for fidelity.")
    # Keep arbitrary-subset deletion as the original primary fidelity score.
    # Add one common ordered-prefix task for all methods, using the fixed order.
    # The empty prefix includes full reconstruction; the full prefix is trivial.
    prefix_masks = (1 << np.arange(k)) - 1
    prefix_removed = 1.0 - ((prefix_masks[:, None] >> np.arange(k)) & 1)
    prefix_delta = pred[selected, None] - v_eval[:, prefix_masks]
    prefix_denominator = float(np.mean(prefix_delta ** 2))
    if prefix_denominator <= 1e-16:
        raise ValueError("The model has insufficient variation for prefix fidelity.")
    point_rows, month_rows, aux_rows = [], [], []
    for method in METHODS:
        explained_delta = attrs[method][selected] @ removed.T
        squared_error = np.mean((explained_delta - delta) ** 2, axis=1)
        squared_ref = np.mean(delta ** 2, axis=1)
        losses = squared_error / denominator
        explained_prefix = attrs[method][selected] @ prefix_removed.T
        prefix_error = np.mean((explained_prefix - prefix_delta) ** 2, axis=1)
        prefix_ref = np.mean(prefix_delta ** 2, axis=1)
        prefix_losses = prefix_error / prefix_denominator
        for pos, (row_id, loss) in enumerate(zip(selected, losses)):
            point_rows.append({"case": tag, "method": method,
                               "row": int(row_id), "date": dates[row_id],
                               "err": float(squared_error[pos]),
                               "ref": float(squared_ref[pos]), "infid": float(loss),
                               "prefix_err": float(prefix_error[pos]),
                               "prefix_ref": float(prefix_ref[pos]),
                               "prefix_infid": float(prefix_losses[pos])})
        for month in np.unique(dates):
            keep = dates == month
            month_rows.append({"case": tag, "method": method, "date": month,
                               "n": int(keep.sum()),
                               "kappa": condition_number(attrs[method][keep])})
        residual = pred - bases[method] - attrs[method].sum(axis=1)
        scale = max(float(np.std(pred)), 1e-12)
        aux_rows.append({"case": tag, "method": method,
                         "recon_nrmse": float(np.sqrt(np.mean(residual ** 2)) / scale),
                         "mean_base": float(np.mean(bases[method]))})
    return pd.DataFrame(point_rows), pd.DataFrame(month_rows), pd.DataFrame(aux_rows)


def explanation_frame(attrs, bases, pred, meta, tag):
    frames = []
    for method in METHODS:
        block = meta.reset_index(drop=True).copy()
        block.insert(0, "case", tag)
        block.insert(1, "method", method)
        block["pred"] = pred
        block["base"] = bases[method]
        for j in range(attrs[method].shape[1]):
            block[f"A{j + 1}"] = attrs[method][:, j]
        frames.append(block)
    return pd.concat(frames, ignore_index=True)

# %% Cell 7: Shared-response conditional Fama-MacBeth experiment
def prepare_designs(attrs, dates):
    """Use identical full-rank months across all four methods."""
    designs, diagnostics = {m: {} for m in METHODS}, []
    for month in np.unique(dates):
        ix = np.flatnonzero(dates == month)
        for method in METHODS:
            a = attrs[method][ix]
            scale = a.std(axis=0, ddof=0)
            ok = len(ix) > a.shape[1] + 2 and np.all(scale > 1e-12)
            weights = None
            if ok:
                z = (a - a.mean(axis=0)) / scale
                d = np.column_stack([np.ones(len(z)), z])
                singular = np.linalg.svd(d, compute_uv=False)
                ok = singular[-1] > CFG["rank_tol"] * singular[0]
                if ok:
                    # A full-rank OLS map, obtained by a stable least-squares solve.
                    weights = np.linalg.lstsq(d, np.eye(len(d)),
                                              rcond=CFG["rank_tol"])[0]
                    designs[method][month] = {"ix": ix, "z": z, "weights": weights}
            diagnostics.append({"date": month, "method": method, "n": len(ix),
                                "valid": bool(ok), "kappa": condition_number(a)})
    common = sorted(set.intersection(*(set(designs[m]) for m in METHODS)))
    return designs, common, pd.DataFrame(diagnostics)


def generate_errors(x_panel, n_reps, seed):
    """Heteroskedastic errors with asset AR terms and a common AR factor."""
    rng = np.random.default_rng(seed)
    nt, n, _ = x_panel.shape
    ar, far = CFG["noise_ar"], CFG["factor_ar"]
    eps = rng.standard_normal((n_reps, nt, n))
    factor = rng.standard_normal((n_reps, nt))
    for month in range(1, nt):
        eps[:, month] = ar * eps[:, month - 1] + np.sqrt(1 - ar * ar) * eps[:, month]
        factor[:, month] = (far * factor[:, month - 1]
                           + np.sqrt(1 - far * far) * factor[:, month])
    scale = 0.7 + 0.3 * np.abs(x_panel[:, :, 0])
    loading = 0.4 * x_panel[:, :, 1]
    return eps * scale[None] + factor[:, :, None] * loading[None]


def hac_mean_se(coefs):
    """Nominal Bartlett HAC diagnostic; finite-sample calibration is separate."""
    nt = coefs.shape[1]
    centered = coefs - coefs.mean(axis=1, keepdims=True)
    long_run = np.mean(centered ** 2, axis=1)
    max_lag = min(CFG["hac_lags"], nt - 1)
    for lag in range(1, max_lag + 1):
        gamma = np.sum(centered[:, lag:] * centered[:, :-lag], axis=1) / nt
        long_run += 2 * (1 - lag / (max_lag + 1)) * gamma
    return np.sqrt(np.maximum(long_run * nt / (nt - 1) / nt, 1e-24))


def simulate_fmb(attrs, dates, x, seed, tag, common_months=None):
    designs, months, validity = prepare_designs(attrs, dates)
    validity.insert(0, "case", tag)
    if common_months is not None:
        months = sorted(set(months).intersection(common_months))
    validity["used_for_inference"] = validity["date"].isin(months)
    if len(months) < CFG["min_months"]:
        raise ValueError(f"Only {len(months)} common valid months for {tag}.")
    sizes = [len(designs["SHAP"][month]["ix"]) for month in months]
    if len(set(sizes)) != 1:
        raise ValueError("The simulation inference panel must be balanced.")
    if not np.all(np.diff(np.asarray(months, dtype=int)) == 1):
        raise ValueError("Inference months must be consecutive; inspect validity.csv.")
    index = np.stack([designs["SHAP"][month]["ix"] for month in months])
    x_panel = x[index]
    target = CFG["target"]
    # Define one response equation from the common original inputs, before any
    # method-specific projection: y(delta) = nuisance_mean + delta * signal + eps.
    # Within-month standardization gives delta the same input-signal units for
    # every prediction model and explanation method.
    x_scale = x_panel.std(axis=1, keepdims=True, ddof=0)
    if np.any(x_scale <= 1e-12):
        raise ValueError("The shared-response inputs need within-month variation.")
    source_z = (x_panel - x_panel.mean(axis=1, keepdims=True)) / x_scale
    signal = source_z[:, :, target]
    nuisance_columns = [j for j in range(CFG["k"]) if j != target]
    nuisance_mean = CFG["nuisance"] * source_z[:, :, nuisance_columns].sum(axis=2)
    maps = {m: np.stack([designs[m][month]["weights"][target + 1]
                         for month in months]) for m in METHODS}
    # The exact finite-panel OLS projection truth is available in a simulation.
    # A coordinate slope has a method-specific baseline and signal loading.
    # Report delta_hat = (mean_slope - null_truth) / signal_loading, so all
    # methods estimate the same imposed original-input effect delta.
    null_monthly = {m: np.einsum("tn,tn->t", maps[m], nuisance_mean)
                    for m in METHODS}
    effect_monthly = {m: np.einsum("tn,tn->t", maps[m], signal)
                      for m in METHODS}
    null_truth = {m: float(null_monthly[m].mean()) for m in METHODS}
    loading = {m: float(effect_monthly[m].mean()) for m in METHODS}
    for method in METHODS:
        if not np.isfinite(loading[method]) or abs(loading[method]) <= CFG["effect_loading_tol"]:
            raise ValueError(
                f"The common effect is unidentified in {tag}/{method}: "
                f"mean projection loading={loading[method]}. "
                "Inspect the fixed coordinate; no alternative feature is selected.")
        keep = validity["method"] == method
        validity.loc[keep, "null_truth"] = null_truth[method]
        validity.loc[keep, "signal_loading"] = loading[method]

    def draws(count, draw_seed):
        collected = {m: [] for m in METHODS}
        for start in range(0, count, CFG["mc_batch"]):
            batch = min(CFG["mc_batch"], count - start)
            eps = generate_errors(x_panel, batch, seed_for(draw_seed, start))
            for method in METHODS:
                collected[method].append(np.einsum("tn,btn->bt", maps[method], eps))
        return {m: np.concatenate(collected[m], axis=0) for m in METHODS}

    def statistics(noise, method, delta):
        # Recompute the HAC denominator for each alternative. The projected
        # signal loading and nuisance projection can vary across months.
        coefficients = (null_monthly[method][None, :]
                        + delta * effect_monthly[method][None, :] + noise)
        coefficient_mean = coefficients.mean(axis=1)
        coefficient_se = hac_mean_se(coefficients)
        estimate = (coefficient_mean - null_truth[method]) / loading[method]
        se = coefficient_se / abs(loading[method])
        return estimate, se, coefficient_mean, coefficient_se

    # This is an explicit known-DGP calibration benchmark. Nominal HAC results
    # remain visible; calibration does not establish a feasible empirical test.
    calibration = draws(CFG["cal_reps"], seed + 10)
    evaluation = draws(CFG["null_reps"], seed + 20)
    nominal_crit = float(student_t.ppf(1 - CFG["alpha"] / 2, len(months) - 1))
    summary_rows, power_rows, raw_rows, sample_rows = [], [], [], []
    # One response realization is reused by every method and prediction model.
    eps_one = generate_errors(x_panel, 1, seed_for(seed, 900))[0]
    y_null = nuisance_mean + eps_one
    for method in METHODS:
        cal_estimate, cal_se, _, _ = statistics(calibration[method], method, 0.0)
        crit = float(np.quantile(np.abs(cal_estimate / cal_se),
                                  1 - CFG["alpha"], method="higher"))
        estimate, se, coefficient_mean, coefficient_se = statistics(
            evaluation[method], method, 0.0)
        t_null = estimate / se
        rejected = np.abs(t_null) > nominal_crit
        calibrated_rejected = np.abs(t_null) > crit
        lo, hi = wilson(int(rejected.sum()), len(rejected), CFG["alpha"])
        adj_lo, adj_hi = wilson(int(calibrated_rejected.sum()), len(rejected), CFG["alpha"])
        rate, adj_rate = float(rejected.mean()), float(calibrated_rejected.mean())
        summary_rows.append({
            "case": tag, "method": method, "months": len(months),
            "size": rate, "size_lo": lo, "size_hi": hi,
            "size_mcse": np.sqrt(rate * (1 - rate) / len(rejected)),
            "adj_size": adj_rate, "adj_size_lo": adj_lo, "adj_size_hi": adj_hi,
            "adj_size_mcse": np.sqrt(adj_rate * (1 - adj_rate) / len(rejected)),
            "bias": float(estimate.mean()),
            "rmse": float(np.sqrt(np.mean(estimate ** 2))),
            "cover": float((np.abs(estimate) <= nominal_crit * se).mean()),
            "adj_cover": float((np.abs(estimate) <= crit * se).mean()),
            "crit": crit, "nominal_crit": nominal_crit,
            "reps": len(rejected), "cal_reps": len(cal_estimate),
            "target": f"X{target + 1}", "coordinate": f"A{target + 1}",
            "null_truth": null_truth[method], "signal_loading": loading[method],
            "scope": "Conditional common-response projection",
            "estimate_units": "Common original-input effect per within-month SD",
            "calibration": "Oracle null simulation under the known error DGP",
        })
        for delta in CFG["effects"]:
            alternative, alternative_se, _, _ = statistics(evaluation[method], method, delta)
            t_alternative = alternative / alternative_se
            hit = np.abs(t_alternative) > crit
            nominal_hit = np.abs(t_alternative) > nominal_crit
            plo, phi = wilson(int(hit.sum()), len(hit), CFG["alpha"])
            nlo, nhi = wilson(int(nominal_hit.sum()), len(hit), CFG["alpha"])
            p, nominal_p = float(hit.mean()), float(nominal_hit.mean())
            error = alternative - delta
            power_rows.append({
                "case": tag, "method": method, "effect": delta,
                "power": p, "lo": plo, "hi": phi,
                "mcse": np.sqrt(p * (1 - p) / len(hit)),
                "nominal_power": nominal_p, "nominal_lo": nlo, "nominal_hi": nhi,
                "bias": float(error.mean()), "rmse": float(np.sqrt(np.mean(error ** 2))),
                "cover": float((np.abs(error) <= nominal_crit * alternative_se).mean()),
                "adj_cover": float((np.abs(error) <= crit * alternative_se).mean()),
                "crit": crit, "nominal_crit": nominal_crit, "reps": len(hit),
                "null_truth": null_truth[method], "signal_loading": loading[method],
                "target": f"X{target + 1}", "coordinate": f"A{target + 1}",
                "scope": "Common response and original-input effect",
            })
        for rep in range(len(estimate)):
            raw_rows.append({
                "case": tag, "method": method, "rep": rep,
                "estimate": estimate[rep], "se": se[rep], "t": t_null[rep],
                "reject": bool(rejected[rep]),
                "calibrated_reject": bool(calibrated_rejected[rep]),
                "coefficient_estimate": coefficient_mean[rep],
                "coefficient_se": coefficient_se[rep],
                "null_truth": null_truth[method], "signal_loading": loading[method],
                "crit": crit, "nominal_crit": nominal_crit,
            })
        for tidx, month in enumerate(months):
            design = designs[method][month]
            direct = design["weights"] @ y_null[tidx]
            for asset in range(y_null.shape[1]):
                sample_rows.append({
                    "case": tag, "method": method, "date": month, "id": asset,
                    "source_row": int(index[tidx, asset]),
                    "y_null": float(y_null[tidx, asset]),
                    "signal": float(signal[tidx, asset]),
                    "nuisance_mean": float(nuisance_mean[tidx, asset]),
                    "epsilon": float(eps_one[tidx, asset]),
                    "beta_hat": float(direct[target + 1]),
                    "null_truth_month": float(null_monthly[method][tidx]),
                    "signal_loading_month": float(effect_monthly[method][tidx]),
                    "null_truth": null_truth[method], "signal_loading": loading[method],
                })
    return (pd.DataFrame(summary_rows), pd.DataFrame(power_rows),
            pd.DataFrame(raw_rows), validity, pd.DataFrame(sample_rows))


def stationary_indices(n_months, n_reps, rng, mean_block=None):
    """Politis-Romano stationary bootstrap of complete month indices."""
    length = (max(2, int(round(n_months ** (1 / 3))))
              if mean_block is None else int(mean_block))
    length = min(max(length, 1), n_months)
    index = np.empty((n_reps, n_months), dtype=int)
    index[:, 0] = rng.integers(0, n_months, n_reps)
    for j in range(1, n_months):
        restart = rng.random(n_reps) < 1.0 / length
        fresh = rng.integers(0, n_months, n_reps)
        index[:, j] = np.where(restart, fresh, (index[:, j - 1] + 1) % n_months)
    return index, length


def percentile_bounds(values):
    tail = (1 - BS["level"]) / 2
    # Order statistics also handle an infinite condition number explicitly.
    return np.quantile(values, [tail, 1 - tail], method="inverted_cdf")


def seed_bootstrap(frame, groups, metrics, name):
    """Resample complete paired run seeds within the supplied grouping keys."""
    seed_ids = sorted(CFG["seeds"])
    rng = np.random.default_rng(np.random.SeedSequence([CFG["seed"], 8800]))
    index = rng.integers(0, len(seed_ids), (BS["reps"], len(seed_ids)))
    records, distributions = [], []
    for group_key, block in frame.groupby(groups, sort=True, observed=True):
        key = group_key if isinstance(group_key, tuple) else (group_key,)
        labels = dict(zip(groups, key))
        values = block.set_index("seed").reindex(seed_ids)[metrics].to_numpy(float)
        if np.isnan(values).any():
            raise ValueError(f"Missing seed metrics in {labels}; inspect per-seed outputs.")
        sampled = values[index].mean(axis=1)
        for j, metric in enumerate(metrics):
            lo, hi = percentile_bounds(sampled[:, j])
            records.append({**labels, "metric": metric,
                            "mean": float(values[:, j].mean()),
                            "sd": (float(values[:, j].std(ddof=1))
                                   if np.isfinite(values[:, j]).all() else np.nan),
                            "lo": float(lo), "hi": float(hi),
                            "seeds": len(seed_ids), "boot": BS["reps"],
                            "unit": "Seed"})
        if BS["save_draws"]:
            draw_table = pd.DataFrame(sampled, columns=metrics)
            draw_table.insert(0, "rep", np.arange(BS["reps"]))
            for label, value in labels.items():
                draw_table[label] = value
            distributions.append(draw_table)
    if distributions:
        save_csv(pd.concat(distributions, ignore_index=True), f"{name}_draws")
    result = pd.DataFrame(records)
    save_csv(result, name)
    return result


def longest_month_span(months):
    """Select a contiguous calendar span for a time-series bootstrap."""
    ordered = sorted(set(str(month) for month in months))
    if not ordered:
        return []
    ordinals = np.array([pd.Period(month, freq="M").ordinal for month in ordered])
    cuts = np.flatnonzero(np.diff(ordinals) != 1) + 1
    chunks = np.split(np.arange(len(ordered)), cuts)
    largest = max(chunks, key=len)
    return [ordered[i] for i in largest]


