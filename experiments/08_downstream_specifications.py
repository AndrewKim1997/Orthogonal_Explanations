    def summarize_state_difference(series, states, resampling):
        series, states = np.asarray(series, float), np.asarray(states, float)
        high, low = np.isfinite(series) & (states == 1), np.isfinite(series) & (states == 0)
        mean = float(series[high].mean() - series[low].mean()) if high.any() and low.any() else np.nan
        output = {"mean": mean, "se": np.nan, "lo": np.nan, "hi": np.nan, "p": np.nan,
            "months": int(high.sum() + low.sum()), "high_months": int(high.sum()), "low_months": int(low.sum()),
            "bootstrap_valid": 0, "status": "Few state months"}
        if min(high.sum(), low.sum()) < SPEC["min_regime_months"]:
            return output
        sampled_values, sampled_states = series[resampling], states[resampling]
        means = []
        for value in [1, 0]:
            finite = np.isfinite(sampled_values) & (sampled_states == value)
            count = finite.sum(axis=1)
            current = np.full(len(resampling), np.nan)
            np.divide(np.where(finite, sampled_values, 0).sum(axis=1), count, out=current, where=count >= 2)
            means.append(current)
        draws = means[0] - means[1]
        draws = draws[np.isfinite(draws)]
        output["bootstrap_valid"] = len(draws)
        if len(draws) < BS["min_valid_share"] * len(resampling):
            output["status"] = "Sparse state resamples"
            return output
        output["lo"], output["hi"] = map(float, percentile_bounds(draws))
        output["se"] = float(draws.std(ddof=1))
        output["p"] = float((1 + np.sum(np.abs(draws - mean) >= abs(mean))) / (1 + len(draws)))
        output["status"] = "OK"
        return output


