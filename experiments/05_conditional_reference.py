class FrozenPredictor:
    def __init__(self, payload, kind, empirical=False):
        self.kind, self.empirical = kind, empirical
        self.estimator = payload["estimator"]
        self.location = float(payload.get("target_mean", 0.0))
        self.scale = float(payload.get("target_scale", 1.0))
        if kind == "XGB":
            self.estimator.set_params(n_jobs=CFG["n_jobs"])

    def predict(self, x):
        x = np.asarray(x, dtype=np.float32 if self.empirical else float)
        if self.kind == "XGB":
            value = self.estimator.get_booster().inplace_predict(np.ascontiguousarray(x), validate_features=False)
        else:
            value = self.estimator.predict(x)
        return self.location + self.scale * np.asarray(value, float)

    def affine_parameters(self):
        if self.kind != "LR":
            raise ValueError("Analytical affine parameters require an OLS predictor.")
        return np.asarray(self.estimator.coef_, float) * self.scale, self.location + self.scale * float(self.estimator.intercept_)


def psd_root(covariance):
    values, vectors = np.linalg.eigh((covariance + covariance.T) / 2)
    return vectors @ np.diag(np.sqrt(np.maximum(values, 0)))


def gaussian_geometry(mean, covariance):
    mean, covariance = np.asarray(mean, float), np.asarray(covariance, float)
    prefixes = []
    for size in range(1, len(mean)):
        cross = covariance[:size, size:]
        gain = np.linalg.solve(covariance[:size, :size], cross)
        conditional_covariance = covariance[size:, size:] - cross.T @ gain
        prefixes.append((size, gain, psd_root(conditional_covariance)))
    return {"mean": mean, "covariance": covariance, "prefixes": prefixes}


def reference_pair(x_reference):
    fitted = LedoitWolf().fit(x_reference)
    mean, covariance = fitted.location_.copy(), fitted.covariance_.copy()
    return {"Full": gaussian_geometry(mean, covariance),
            "Diagonal": gaussian_geometry(mean, np.diag(np.diag(covariance)))}


class OrderedGaussianCOLA:
    def __init__(self, geometry, predictor, base_draws, seed, analytical=False):
        self.geometry, self.predictor, self.analytical = geometry, predictor, analytical
        self.mean, self.k = geometry["mean"], len(geometry["mean"])
        if analytical:
            self.weight, self.intercept = predictor.affine_parameters()
            self.base = float(self.intercept + self.mean @ self.weight)
        else:
            rng = np.random.default_rng(seed)
            background = rng.multivariate_normal(self.mean, geometry["covariance"], int(base_draws))
            self.base = float(predictor.predict(background).mean())

    def values(self, x, draws, seed):
        x = np.asarray(x, dtype=np.float32 if self.predictor.empirical else float)
        if int(draws) < 2 or int(draws) % 2:
            raise ValueError("The antithetic conditional draw count must be even and at least two.")
        rng = np.random.default_rng(seed)
        values = np.empty((len(x), self.k + 1), float)
        values[:, 0], values[:, -1] = self.base, self.predictor.predict(x)
        for size, gain, root in self.geometry["prefixes"]:
            center = self.mean[size:] + (x[:, :size] - self.mean[:size]) @ gain
            if self.analytical:
                values[:, size] = self.intercept + x[:, :size] @ self.weight[:size] + center @ self.weight[size:]
                continue
            noise = rng.standard_normal((int(draws) // 2, self.k - size))
            noise = np.concatenate([noise, -noise], axis=0) @ root.T
            for start in range(0, len(x), CFG["prediction_batch"]):
                stop = min(start + CFG["prediction_batch"], len(x))
                filled = np.broadcast_to(x[start:stop, None, :], (stop - start, int(draws), self.k)).copy()
                filled[:, :, size:] = center[start:stop, None, :] + noise[None, :, :]
                values[start:stop, size] = self.predictor.predict(filled.reshape(-1, self.k)).reshape(stop - start, int(draws)).mean(axis=1)
        return values

    def explain(self, x, draws, seed):
        values = self.values(x, draws, seed)
        return np.diff(values, axis=1), values[:, -1]


def full_condition_number(attributions, intercept=False):
    attributions = np.asarray(attributions, float)
    if len(attributions) <= attributions.shape[1] or not np.isfinite(attributions).all():
        return np.inf
    scale = attributions.std(axis=0, ddof=0)
    if np.any(scale <= 1e-12):
        return np.inf
    design = (attributions - attributions.mean(axis=0)) / scale
    if intercept:
        design = np.column_stack([np.ones(len(design)), design])
    singular = np.linalg.svd(design, compute_uv=False)
    return float(singular[0] / singular[-1]) if singular[-1] > CFG["rank_tol"] * singular[0] else np.inf


def monthly_design(attributions):
    scales = attributions.std(axis=0, ddof=0)
    active = np.flatnonzero(scales > 1e-12)
    if len(attributions) < max(CFG["min_cross_section"], len(active) + 3) or not len(active):
        return None, active, "Insufficient cross-sectional variation"
    standardized = (attributions[:, active] - attributions[:, active].mean(axis=0)) / scales[active]
    design = np.column_stack([np.ones(len(standardized)), standardized])
    singular = np.linalg.svd(design, compute_uv=False)
    if singular[-1] <= CFG["rank_tol"] * singular[0]:
        return None, active, "Rank deficient"
    return design, active, "OK"


def quantile_fit(design, outcome, tau):
    scale = max(float(np.std(outcome)), 1e-4)
    fit = linprog(-outcome / scale, A_eq=sparse.csr_matrix(design.T),
                  b_eq=np.zeros(design.shape[1]), bounds=(tau - 1, tau), method="highs",
                  options={"presolve": True, "time_limit": CFG["qr_time_limit"],
                           "primal_feasibility_tolerance": 1e-8,
                           "dual_feasibility_tolerance": 1e-8})
    if not fit.success:
        return None, str(fit.message)
    beta = -np.asarray(fit.eqlin.marginals) * scale
    residual = outcome - design @ beta
    primal = float(np.maximum(tau * residual, (tau - 1) * residual).sum())
    dual = float(-fit.fun * scale)
    if not np.isfinite(beta).all() or abs(primal - dual) > 1e-5 * max(1.0, abs(primal), abs(dual)):
        return None, "Primal-dual objective gap"
    return beta, "OK"


