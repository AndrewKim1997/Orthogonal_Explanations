    def fit_selected_payload(kind, x_train, y_train, x_valid, y_valid, x_pretest, y_pretest,
                             seed, empirical=False):
        """Run the main validation rule once, then freeze the selected predictor."""
        y_train, y_valid, y_pretest = [np.asarray(y, float) for y in [y_train, y_valid, y_pretest]]
        tuning = []
        if kind == "MLP":
            location, scale = float(y_train.mean()), max(float(y_train.std()), 1e-12)
            candidate = new_estimator(kind, None, seed, len(y_train))
            normalized_y = (y_train - location) / scale
            for epoch in range(1, max(CFG["mlp_epochs"]) + 1):
                candidate.partial_fit(x_train, normalized_y)
                if epoch in CFG["mlp_epochs"]:
                    predicted = location + scale * candidate.predict(x_valid)
                    tuning.append({"parameter": "epochs", "value": epoch,
                                   "valid_mse": float(np.mean((y_valid - predicted) ** 2))})
        else:
            for parameter in ([0] if kind == "LR" else CFG["trees"]):
                candidate = new_estimator(kind, parameter, seed, len(y_train))
                candidate.fit(x_train, y_train)
                predicted = FrozenPredictor({"estimator": candidate}, kind, empirical).predict(x_valid)
                tuning.append({"parameter": "none" if kind == "LR" else "trees", "value": parameter,
                               "valid_mse": float(np.mean((y_valid - predicted) ** 2))})
        best = min(range(len(tuning)), key=lambda position: tuning[position]["valid_mse"])
        for position, row in enumerate(tuning):
            row["selected"] = position == best
        selected = tuning[best]["value"]
        estimator = new_estimator(kind, selected, seed, len(y_pretest))
        location, scale = 0.0, 1.0
        if kind == "MLP":
            location, scale = float(y_pretest.mean()), max(float(y_pretest.std()), 1e-12)
            normalized_y = (y_pretest - location) / scale
            for _ in range(int(selected)):
                estimator.partial_fit(x_pretest, normalized_y)
        else:
            estimator.fit(x_pretest, y_pretest)
        return {"estimator": estimator, "model": kind, "kind": kind,
                "target_mean": location, "target_scale": scale,
                "selected_parameter": selected, "tuning": tuning}


