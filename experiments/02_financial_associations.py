def market_states(market_path, initial_train_dates, months):
    source = pd.read_csv(market_path)
    proxy = pd.Series(source["market"].to_numpy(float), index=parse_month(source["return_date"]))
    if proxy.index.duplicated().any():
        raise ValueError("The French 100 market proxy has duplicate calendar months.")
    calendar = pd.period_range(proxy.index.min(), proxy.index.max(), freq="M")
    proxy = proxy.sort_index().reindex(calendar)
    # At row's realized-return month r, the state may use realized returns through r-1.
    vol = proxy.shift(1).rolling(CFG["vol_window"], min_periods=CFG["vol_min_history"]).std(ddof=1)
    train_vol = vol.reindex(initial_train_dates.unique()).dropna()
    if len(train_vol) < 60:
        raise ValueError("Initial training history is insufficient for a fixed state cutoff.")
