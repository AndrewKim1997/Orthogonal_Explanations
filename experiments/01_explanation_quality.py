def make_sim_panel(rho, dgp, seed):
    rng = np.random.default_rng(seed)
    k, n = CFG["k"], CFG["n_assets"]
    nt = CFG["train_months"] + CFG["valid_months"] + CFG["test_months"]
    cov = (1 - rho) * np.eye(k) + rho * np.ones((k, k))
    chol = np.linalg.cholesky(cov)
    innovations = rng.standard_normal((nt, n, k)) @ chol.T
    x = np.empty_like(innovations)
    x[0] = innovations[0]
    for month in range(1, nt):
        x[month] = (CFG["x_ar"] * x[month - 1]
                    + np.sqrt(1 - CFG["x_ar"] ** 2) * innovations[month])
    flat = x.reshape(-1, k)
    signal = 0.7 * flat[:, 0] - 0.5 * flat[:, 1] + 0.35 * flat[:, 2]
    signal += 0.2 * flat[:, 3] - 0.15 * flat[:, 4] + 0.1 * flat[:, 5]
    if dgp == "Nonlinear":
        signal += (0.45 * np.sin(flat[:, 0])
                   + 0.3 * (flat[:, 2] ** 2 - 1)
                   + 0.35 * flat[:, 3] * flat[:, 4])
    noise = rng.standard_normal(len(flat)) * CFG["train_noise"]
    noise *= 0.7 + 0.3 * np.abs(flat[:, 0])
    frame = pd.DataFrame(flat, columns=[f"X{j + 1}" for j in range(k)])
    frame.insert(0, "id", np.tile(np.arange(n), nt))
    frame.insert(1, "date", np.repeat(np.arange(nt), n))
    frame["y"] = signal + noise
    return frame


class ReturnPredictor:
    """Expose every prediction and attribution in the original response units."""

    def __init__(self, estimator, kind, target_mean=0.0, target_scale=1.0):
        self.estimator, self.kind = estimator, kind
        self.target_mean, self.target_scale = target_mean, target_scale

    def predict(self, x):
        pred = np.asarray(self.estimator.predict(x), dtype=float)
        return self.target_mean + self.target_scale * pred


