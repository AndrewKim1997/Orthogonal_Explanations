def monthly_design(attr):
    scale = attr.std(axis=0, ddof=0)
    active = np.flatnonzero(scale > 1e-12)
    z = np.zeros_like(attr)
    if len(active):
        z[:, active] = (attr[:, active] - attr[:, active].mean(axis=0)) / scale[active]
    if len(attr) < max(CFG["min_cross_section"], len(active) + 3):
        return None, z, active, np.inf, np.nan, "Few assets"
    if not len(active):
        return None, z, active, np.inf, np.nan, "Constant explanations"
    design = np.column_stack([np.ones(len(attr)), z[:, active]])
    singular = np.linalg.svd(design, compute_uv=False)
    condition = float(singular[0] / singular[-1]) if singular[-1] > 0 else np.inf
    if singular[-1] <= CFG["rank_tol"] * singular[0]:
        return None, z, active, condition, np.inf, "Rank deficient"
    # SVD avoids squaring the condition number through normal-equation inversion.
    _, slope_singular, slope_vectors = np.linalg.svd(z[:, active], full_matrices=False)
    vif = len(z) * np.square(slope_vectors.T / slope_singular).sum(axis=1)
    max_vif = float(vif.max())
    return design, z, active, condition, max_vif, "OK"


def quantile_fit(design, y, tau):
    """Exact unpenalized quantile regression through its smaller dual LP."""
    scale = max(float(np.std(y)), 1e-4)
    result = linprog(-y / scale, A_eq=sparse.csr_matrix(design.T), b_eq=np.zeros(design.shape[1]),
        bounds=(tau - 1, tau), method="highs", options={"presolve": True,
        "time_limit": CFG["qr_time_limit"], "primal_feasibility_tolerance": 1e-8,
        "dual_feasibility_tolerance": 1e-8})
    if not result.success:
        return None, str(result.message)
    beta = -np.asarray(result.eqlin.marginals) * scale
    residual = y - design @ beta
    primal = float(np.maximum(tau * residual, (tau - 1) * residual).sum())
    dual = float(-result.fun * scale)
    if not np.isfinite(beta).all() or abs(primal - dual) > 1e-5 * max(1.0, abs(primal), abs(dual)):
        return None, "Primal-dual objective gap"
    return beta, "OK"


def sort_returns(signal, y):
    groups = CFG["groups"]
    if len(signal) < groups * CFG["min_bin"]:
        return np.full(groups, np.nan), np.zeros(groups, int), "Few assets"
    cuts = np.quantile(signal, np.arange(1, groups) / groups)
    if len(np.unique(cuts)) != groups - 1:
        return np.full(groups, np.nan), np.zeros(groups, int), "Tied cuts"
    assignment = np.searchsorted(cuts, signal, side="left")
    sizes = np.bincount(assignment, minlength=groups)
    if sizes.min() < CFG["min_bin"]:
        return np.full(groups, np.nan), sizes, "Small group"
    return np.array([y[assignment == group].mean() for group in range(groups)]), sizes, "OK"


def two_way_demean(values, entities, dates):
    residual = np.asarray(values, float).copy()
    groups = [np.asarray(entities, int), np.asarray(dates, int)]
    counts = [np.bincount(group) for group in groups]
    tolerance = CFG["within_tol"] * max(1.0, float(np.abs(residual).max()))
    for iteration in range(CFG["within_max_iter"]):
        before = residual.copy()
        for group, count in zip(groups, counts):
            sums = np.zeros((len(count), residual.shape[1]))
            np.add.at(sums, group, residual)
            residual -= (sums / count[:, None])[group]
        if float(np.max(np.abs(residual - before))) <= tolerance:
            return residual, iteration + 1
    return None, CFG["within_max_iter"]


def cluster_meat(scores, group):
    labels, inverse = np.unique(group, return_inverse=True)
    sums = np.zeros((len(labels), scores.shape[1]))
    np.add.at(sums, inverse, scores)
    return sums.T @ sums, len(labels)


def twfe_fit(frame, z):
    """Within OLS with entity and month fixed effects; two-way clustered CIs."""
    n, k = z.shape
    output = {"coef": np.full(k, np.nan), "se": np.full(k, np.nan),
              "lo": np.full(k, np.nan), "hi": np.full(k, np.nan), "p": np.full(k, np.nan),
              "feature_status": ["Unsupported"] * k, "status": "Unsupported", "condition": np.inf}
    entity, entity_labels = pd.factorize(frame["id"], sort=True)
    date, date_labels = pd.factorize(frame["return_date"], sort=True)
    ne, nt = len(entity_labels), len(date_labels)
    output.update({"rows": n, "entities": ne, "months": nt})
    if ne < 2 or nt < BS["min_months"]:
        output["status"] = "Few entity/month clusters"
        return output
    within, iterations = two_way_demean(np.column_stack([frame["y"].to_numpy(float), z]), entity, date)
    output["within_iterations"] = iterations
    if within is None:
        output["status"] = "Within transformation did not converge"
        return output
    yw, zw = within[:, 0], within[:, 1:]
    active = np.flatnonzero(zw.std(axis=0) > 1e-12)
    if not len(active):
        output["status"] = "No within variation"
        return output
    design = zw[:, active]
    _, singular, right_vectors = np.linalg.svd(design, full_matrices=False)
    output["condition"] = float(singular[0] / singular[-1]) if singular[-1] > 0 else np.inf
    if singular[-1] <= CFG["rank_tol"] * singular[0]:
        output["status"] = "Within design rank deficient"
        return output
    # Entity-time connected components determine the exact absorbed FE rank.
    adjacency = sparse.coo_matrix((np.ones(2 * n),
        (np.r_[entity, ne + date], np.r_[ne + date, entity])), shape=(ne + nt, ne + nt)).tocsr()
    components = connected_components(adjacency, directed=False, return_labels=False)
    absorbed_rank = ne + nt - int(components)
    residual_df = n - absorbed_rank - len(active)
    output.update({"absorbed_rank": absorbed_rank, "residual_df": residual_df,
                   "active_features": len(active), "inference_df": min(ne, nt) - 1})
    if residual_df <= 0:
        output["status"] = "No residual degrees of freedom"
        return output
    beta = np.linalg.lstsq(design, yw, rcond=CFG["rank_tol"])[0]
    output["coef"][active] = beta
    residual = yw - design @ beta
    scores = design * residual[:, None]
    terms = [cluster_meat(scores, entity), cluster_meat(scores, date),
             cluster_meat(scores, entity.astype(np.int64) * nt + date)]
    corrected = [meat * (clusters / (clusters - 1)) * ((n - 1) / residual_df)
                 for meat, clusters in terms]
    bread = (right_vectors.T / np.square(singular)) @ right_vectors
    covariance = bread @ (corrected[0] + corrected[1] - corrected[2]) @ bread
    diagonal = np.diag((covariance + covariance.T) / 2)
    critical = student_t.ppf(1 - (1 - BS["level"]) / 2, min(ne, nt) - 1)
    for position, feature in enumerate(active):
        if not np.isfinite(diagonal[position]) or diagonal[position] <= 0:
            output["feature_status"][feature] = "Nonpositive clustered variance"
            continue
        se = math.sqrt(float(diagonal[position]))
        output["se"][feature] = se
        output["lo"][feature], output["hi"][feature] = beta[position] - critical * se, beta[position] + critical * se
        output["p"][feature] = float(2 * student_t.sf(abs(beta[position] / se), min(ne, nt) - 1))
        output["feature_status"][feature] = "OK"
    for feature in set(range(k)) - set(active):
        output["feature_status"][feature] = "No within variation"
    output["status"] = "OK"
    return output


