def monthly_design(attr):
    scale = attr.std(axis=0, ddof=0)
    active = np.flatnonzero(scale > 1e-12)
    if len(attr) < max(CFG["min_cross_section"], len(active) + 3):
        return None, active, np.inf, "Few portfolios"
    if not len(active):
        return None, active, np.inf, "No varying explanation columns"
    z = (attr[:, active] - attr[:, active].mean(axis=0)) / scale[active]
    design = np.column_stack([np.ones(len(attr)), z])
    singular = np.linalg.svd(design, compute_uv=False)
    kappa = float(singular[0] / singular[-1]) if singular[-1] > 0 else np.inf
    if singular[-1] <= CFG["rank_tol"] * singular[0]:
        return None, active, kappa, "Rank deficient"
    return design, active, kappa, "OK"

def quantile_fit(design, y, tau):
    """Exact unpenalized QR via the smaller dual LP, with objective-gap check.

    max y'u s.t. D'u=0, tau-1 <= u <= tau. HiGHS equality marginals have
    the opposite sign to primal regression coefficients in this minimization.
    This has n variables and p equalities instead of p+2n variables/n equalities.
    """
    scale = max(float(np.std(y)), 1e-4)
    result = linprog(-y / scale, A_eq=sparse.csr_matrix(design.T),
        b_eq=np.zeros(design.shape[1]), bounds=(tau - 1, tau), method="highs",
        options={"presolve": True, "time_limit": CFG["qr_time_limit"],
                 "primal_feasibility_tolerance": 1e-8,
                 "dual_feasibility_tolerance": 1e-8})
    if not result.success:
        return None, str(result.message)
    beta = -np.asarray(result.eqlin.marginals) * scale
    residual = y - design @ beta
    primal = float(np.maximum(tau * residual, (tau - 1) * residual).sum())
    dual = float(-result.fun * scale)
    if (not np.isfinite(beta).all() or abs(primal - dual) > 1e-5 * max(1.0, abs(primal), abs(dual))):
        return None, "Primal-dual objective gap"
    return beta, "OK"

def sort_returns(signal, y):
    groups = CFG["groups"]
    if len(signal) < groups * CFG["min_bin"]:
        return np.full(groups, np.nan), np.zeros(groups, int), "Few portfolios"
    cuts = np.quantile(signal, np.arange(1, groups) / groups)
    if len(np.unique(cuts)) != groups - 1:
        return np.full(groups, np.nan), np.zeros(groups, int), "Tied cuts"
    assignment = np.searchsorted(cuts, signal, side="left")
    counts = np.bincount(assignment, minlength=groups)
    if counts.min() < CFG["min_bin"]:
        return np.full(groups, np.nan), counts, "Small group"
    return np.array([y[assignment == g].mean() for g in range(groups)]), counts, "OK"

def analyze_month(attr, y, plot_index):
    k = attr.shape[1]
    fm, qr = np.full(k, np.nan), np.full((len(CFG["quantiles"]), k), np.nan)
    portfolios = np.full((len(plot_index), CFG["groups"]), np.nan)
    design, active, kappa, status = monthly_design(attr)
    diagnostics = [{"analysis": "FM", "status": status, "n": len(y), "kappa": kappa,
                    "active_k": len(active), "inactive_columns": ",".join(
                        f"X{j + 1}" for j in range(k) if j not in active)}]
    if design is not None:
        beta = np.linalg.lstsq(design, y, rcond=CFG["rank_tol"])[0]
        fm[active] = beta[1:]
        for qi, tau in enumerate(CFG["quantiles"]):
            beta, result = quantile_fit(design, y, tau)
            diagnostics.append({"analysis": "QR", "tau": tau, "status": result, "n": len(y)})
            if beta is not None:
                qr[qi, active] = beta[1:]
    for p, j in enumerate(plot_index):
        portfolios[p], counts, result = sort_returns(attr[:, j], y)
        diagnostics.append({"analysis": "Sort", "feature": f"X{j + 1}", "status": result,
                            "n": len(y), "min_group_n": int(counts.min())})
    return fm, qr, portfolios, diagnostics

