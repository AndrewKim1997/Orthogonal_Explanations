def annual_indices(return_dates, year):
    """Splits in realized-return months; no target from the forecast year is fitted."""
    anchor = pd.Period(f"{year}-01", freq="M")
    validation_start = anchor - int(DATA["validation_months"])
    final_cutoff = anchor - int(DATA["purge_months"])
    start = pd.Period(DATA["train_start"], freq="M")
    train = np.flatnonzero((return_dates >= start) & (return_dates < validation_start))
    valid = np.flatnonzero((return_dates >= validation_start) & (return_dates < final_cutoff))
    pretest = np.flatnonzero((return_dates >= start) & (return_dates < final_cutoff))
    target = np.flatnonzero((return_dates >= anchor) & (return_dates <= anchor + 11)
                           & (return_dates >= pd.Period(DATA["test_start"], freq="M"))
                           & (return_dates <= pd.Period(DATA["test_end"], freq="M")))
    if not len(train) or not len(valid) or not len(target):
        raise ValueError(f"Empty chronological split for {year}.")
    return train, valid, pretest, target

def initial_features(panel, names, train_index):
    requested = list(names) if DATA["features"] is None else list(DATA["features"])
    unknown = set(requested) - set(names)
    if unknown:
        raise ValueError(f"Unknown source characteristics: {sorted(unknown)}")
    sample = panel.iloc[train_index]
    retained, rows = [], []
    for name in requested:
        values = sample[name].to_numpy()
        observed = values[np.isfinite(values)]
        good = len(observed) > 1 and np.ptp(observed) > 1e-12
        rows.append({"source": name, "observed_initial_train": len(observed),
                     "included": good, "reason": "OK" if good else "Missing or constant in initial training"})
        if good:
            retained.append(name)
    if len(retained) < CFG["plot_features"]:
        raise ValueError("Initial training has too few usable characteristics.")
    return retained, pd.DataFrame(rows)

