def stationary_indices(n_months, n_reps, rng, mean_block=None):
    length = max(2, int(round(n_months ** (1 / 3)))) if mean_block is None else int(mean_block)
    length = min(max(1, length), n_months)
    index = np.empty((n_reps, n_months), dtype=int)
    index[:, 0] = rng.integers(0, n_months, n_reps)
    for j in range(1, n_months):
        restart = rng.random(n_reps) < 1 / length
        fresh = rng.integers(0, n_months, n_reps)
        index[:, j] = np.where(restart, fresh, (index[:, j - 1] + 1) % n_months)
    return index, length

def safe_average(values, axis, minimum=1):
    finite = np.isfinite(values)
    count = finite.sum(axis=axis)
    numerator = np.where(finite, values, 0.0).sum(axis=axis)
    result = np.full(np.shape(numerator), np.nan, dtype=float)
    np.divide(numerator, count, out=result, where=count >= minimum)
    return result, count

def summarize_series(seed_series, states, boot_index, block_length, state_value=None, difference=False):
    s = seed_series.shape[0]
    supported = np.isfinite(seed_series).all(axis=0)
    series = np.where(supported, seed_series.mean(axis=0), np.nan)
    high, low = supported & (states == 1), supported & (states == 0)
    if difference:
        usable = high | low
    elif state_value is not None:
        usable = supported & (states == state_value)
    else:
        usable = supported
    n = int(usable.sum())
    out = {"months": n, "high": int(high.sum()), "low": int(low.sum()), "seeds": s,
           "boot": BS["reps"], "block": block_length, "mean": np.nan, "seed_sd": np.nan,
           "boot_se": np.nan, "lo": np.nan, "hi": np.nan, "p": np.nan,
           "boot_valid": 0, "status": "Few months"}
    if n == 0:
        return out
    if difference:
        if not high.any() or not low.any():
            out["status"] = "Missing state"
            return out
        per_seed = seed_series[:, high].mean(axis=1) - seed_series[:, low].mean(axis=1)
    else:
        per_seed = seed_series[:, usable].mean(axis=1)
    out["mean"] = float(per_seed.mean())
    out["seed_sd"] = float(per_seed.std(ddof=1)) if s > 1 else 0.0
    if difference and min(high.sum(), low.sum()) < CFG["min_regime_months"]:
        out["status"] = "Few state months"
        return out
    if state_value is not None:
        minimum = CFG["min_regime_months"]
    else:
        minimum = BS["min_months"]
    if n < minimum:
        return out
    samples = series[boot_index]
    if difference:
        sampled_states = states[boot_index]
        high_mean, _ = safe_average(np.where(sampled_states == 1, samples, np.nan), 1, minimum=2)
        low_mean, _ = safe_average(np.where(sampled_states == 0, samples, np.nan), 1, minimum=2)
        draws = high_mean - low_mean
    else:
        if state_value is not None:
            samples = np.where(states[boot_index] == state_value, samples, np.nan)
        draws, _ = safe_average(samples, 1, minimum=max(3, minimum // 2))
    finite = draws[np.isfinite(draws)]
    out["boot_valid"] = len(finite)
    if len(finite) < BS["min_valid_share"] * BS["reps"]:
        out["status"] = "Sparse resamples"
        return out
    tail = (1 - BS["level"]) / 2
    out["lo"], out["hi"] = map(float, np.quantile(finite, [tail, 1 - tail], method="inverted_cdf"))
    out["boot_se"] = float(finite.std(ddof=1))
    out["p"] = float((1 + np.sum(np.abs(finite - out["mean"]) >= abs(out["mean"]))) / (1 + len(finite)))
    out["status"] = "OK"
    return out

def holm(pvalues):
    """Holm adjustment over the full predeclared family, including missing slots."""
    pvalues = np.asarray(pvalues, float)
    filled = np.where(np.isfinite(pvalues), pvalues, 1.0)
    order = np.argsort(filled, kind="stable")
    adjusted = np.minimum(1, np.maximum.accumulate(filled[order] * np.arange(len(filled), 0, -1)))
    output = np.empty_like(adjusted)
    output[order] = adjusted
    output[~np.isfinite(pvalues)] = np.nan
    return output

def as_basis_points(frame):
    frame = frame.copy()
    for name in ["mean", "seed_sd", "boot_se", "lo", "hi"]:
        if name in frame:
            frame[name] *= CFG["bps"]
    return frame

