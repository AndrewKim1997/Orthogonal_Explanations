def place_legend_header(fig, axes, handles, ncol=3, hspace=0.50, wspace=0.38):
    """Preserve the physical panel canvas and add a measured legend header."""
    # Layout engines can override subplots_adjust or ignore figure legends.
    # Use one explicit physical layout for both saved files and inline figures.
    with mpl.rc_context({"figure.constrained_layout.use": False, "figure.autolayout": False}):
        fig.set_layout_engine(None)
    base_width, base_height = map(float, fig.get_size_inches())
    panel_axes = list(np.asarray(axes, dtype=object).ravel())
    side_pad, bottom_pad, top_pad, legend_gap = 0.12, 0.08, 0.12, 0.18
    fig.subplots_adjust(left=0.12, right=0.98, bottom=0.64 / base_height,
                        top=(base_height - 0.34) / base_height,
                        hspace=hspace, wspace=wspace)
    panel_rectangles = [
        (ax.get_position().x0 * base_width, ax.get_position().y0 * base_height,
         ax.get_position().width * base_width, ax.get_position().height * base_height)
        for ax in panel_axes
    ]
    columns = min(max(1, int(ncol)), len(handles))
    legend = None
    while True:
        if legend is not None:
            legend.remove()
        legend = fig.legend(
            handles=handles, loc="upper center", bbox_to_anchor=(0.5, 1.0),
            bbox_transform=fig.transFigure, ncol=columns, frameon=False,
            fontsize=8, borderaxespad=0.0, borderpad=0.20, labelspacing=0.45,
            columnspacing=1.10, handlelength=1.8, handletextpad=0.50,
        )
        fig.canvas.draw()
        renderer = fig.canvas.get_renderer()
        legend_box = legend.get_window_extent(renderer)
        legend_width, legend_height = legend_box.width / fig.dpi, legend_box.height / fig.dpi
        if legend_width <= base_width - 2 * side_pad or columns == 1:
            break
        columns -= 1
    panel_boxes = [ax.get_tightbbox(renderer) for ax in panel_axes]
    panel_boxes = [box for box in panel_boxes if box is not None]
    left_extra = max(0.0, side_pad - min(box.x0 / fig.dpi for box in panel_boxes))
    right_extra = max(0.0, max(box.x1 / fig.dpi for box in panel_boxes) - base_width + side_pad)
    bottom_extra = max(0.0, bottom_pad - min(box.y0 / fig.dpi for box in panel_boxes))
    panel_width = base_width + left_extra + right_extra
    final_width = max(panel_width, legend_width + 2 * side_pad)
    horizontal_offset = left_extra + (final_width - panel_width) / 2
    panel_ceiling = max(box.y1 / fig.dpi for box in panel_boxes) + bottom_extra
    header_bottom = max(base_height + bottom_extra, panel_ceiling) + legend_gap
    final_height = header_bottom + legend_height + top_pad

    def apply_canvas(height):
        fig.set_size_inches(final_width, height, forward=True)
        for ax, (left, bottom, width, panel_height) in zip(panel_axes, panel_rectangles):
            ax.set_position([(left + horizontal_offset) / final_width,
                             (bottom + bottom_extra) / height,
                             width / final_width, panel_height / height])
        legend.set_bbox_to_anchor((0.5, 1.0 - top_pad / height), transform=fig.transFigure)

    apply_canvas(final_height)
    # Font backends can differ; reserve the measured separation after resizing.
    for _ in range(3):
        fig.canvas.draw()
        renderer = fig.canvas.get_renderer()
        current_top = max(ax.get_tightbbox(renderer).y1 / fig.dpi for ax in panel_axes)
        current_legend_bottom = legend.get_window_extent(renderer).y0 / fig.dpi
        missing = current_top + legend_gap - current_legend_bottom
        if missing <= 0.001:
            break
        final_height += missing + 0.02
        apply_canvas(final_height)
    fig.canvas.draw()
    return {
        "figure_inches": [float(final_width), float(final_height)],
        "panel_canvas_inches": [base_width, base_height],
        "legend_columns": columns,
        "legend_rows": int(math.ceil(len(handles) / columns)),
        "legend_height_inches": float(legend_height),
        "minimum_legend_gap_inches": legend_gap,
        "layout_engine": "none",
    }



