def quantile_coefficients(design, outcome, tau):
    # The fallback solves the same Koenker-Bassett quantile-regression objective.
    use_lp = False
    try:
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            fit = sm.QuantReg(outcome, design).fit(q=tau, max_iter=1000, p_tol=1e-7)
        use_lp = (not np.isfinite(fit.params).all()
                  or any(issubclass(item.category, (ConvergenceWarning, IterationLimitWarning))
                         for item in caught))
        if not use_lp:
            return np.asarray(fit.params, dtype=float), "statsmodels.QuantReg"
    except np.linalg.LinAlgError:
        use_lp = True
    scale = max(float(np.std(outcome)), 1e-6)
    solution = linprog(
        -outcome / scale, A_eq=sparse.csr_matrix(design.T),
        b_eq=np.zeros(design.shape[1]), bounds=(tau - 1.0, tau), method="highs",
        options={"presolve": True, "time_limit": 30.0,
                 "primal_feasibility_tolerance": 1e-8,
                 "dual_feasibility_tolerance": 1e-8})
    if not solution.success:
        raise RuntimeError(f"Quantile regression failed at tau={tau}: {solution.message}")
    coefficient = -np.asarray(solution.eqlin.marginals, dtype=float) * scale
    if not np.isfinite(coefficient).all():
        raise RuntimeError(f"Quantile regression returned nonfinite coefficients at tau={tau}.")
    return coefficient, "Koenker-Bassett linear programming"


def hac_mean(values, context):
    values = np.asarray(values, dtype=float)
    if len(values) != T or not np.isfinite(values).all():
        raise RuntimeError(f"{context}: the monthly series is incomplete.")
    fit = sm.OLS(values, np.ones((T, 1))).fit(
        cov_type="HAC", cov_kwds={"maxlags": CFG["hac_lags"], "use_correction": True},
        use_t=True)
    interval = np.asarray(fit.conf_int(), dtype=float)[0]
    return check_estimate(
        {"coef": float(fit.params[0]), "se": float(fit.bse[0]),
         "statistic": float(fit.tvalues[0]), "pvalue": float(fit.pvalues[0]),
         "lower": float(interval[0]), "upper": float(interval[1])}, context)


