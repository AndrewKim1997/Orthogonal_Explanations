def fit_predictor(kind, x_train, y_train, x_valid, y_valid, seed, tag):
    """Select XGB trees or MLP epochs on validation, then refit on pre-test X/y."""
    y_train, y_valid = np.asarray(y_train, float), np.asarray(y_valid, float)
    x_pretest = np.concatenate([x_train, x_valid])
    y_pretest = np.concatenate([y_train, y_valid])
    rows = []
    if kind == "LR":
        candidate = LinearRegression().fit(x_train, y_train)
        loss = float(mean_squared_error(y_valid, candidate.predict(x_valid)))
        rows.append({"case": tag, "model": kind, "parameter": "none",
                     "value": 0, "valid_mse": loss, "selected": True})
        final = ReturnPredictor(LinearRegression().fit(x_pretest, y_pretest), kind)
    elif kind == "XGB":
        for trees in CFG["trees"]:
            candidate = new_xgb(trees, seed).fit(x_train, y_train)
            loss = float(mean_squared_error(y_valid, candidate.predict(x_valid)))
            rows.append({"case": tag, "model": kind, "parameter": "trees",
                         "value": int(trees), "valid_mse": loss})
        best = min(range(len(rows)), key=lambda i: rows[i]["valid_mse"])
        for i, row in enumerate(rows):
            row["selected"] = i == best
        final = ReturnPredictor(
            new_xgb(rows[best]["value"], seed).fit(x_pretest, y_pretest), kind)
    elif kind == "MLP":
        epochs = sorted(set(int(value) for value in CFG["mlp_epochs"]))
        if not epochs or epochs[0] < 1:
            raise ValueError("MLP epoch candidates must be positive integers.")
        # Response scaling is fitted to training data during selection.
        location, scale = float(y_train.mean()), max(float(y_train.std()), 1e-12)
        candidate = new_mlp(seed, len(y_train))
        scaled_y = (y_train - location) / scale
        for epoch in range(1, epochs[-1] + 1):
            candidate.partial_fit(x_train, scaled_y)
            if epoch in epochs:
                prediction = location + scale * candidate.predict(x_valid)
                loss = float(mean_squared_error(y_valid, prediction))
                rows.append({"case": tag, "model": kind, "parameter": "epochs",
                             "value": epoch, "valid_mse": loss})
        best = min(range(len(rows)), key=lambda i: rows[i]["valid_mse"])
        for i, row in enumerate(rows):
            row["selected"] = i == best
        # Fresh fit: its target scaler uses training + validation only.
        location = float(y_pretest.mean())
        scale = max(float(y_pretest.std()), 1e-12)
        estimator = new_mlp(seed, len(y_pretest))
        for _ in range(rows[best]["value"]):
            estimator.partial_fit(x_pretest, (y_pretest - location) / scale)
        final = ReturnPredictor(estimator, kind, location, scale)
    else:
        raise ValueError(f"Unknown prediction model: {kind}")
    if not np.isfinite(final.predict(x_pretest)).all():
        raise FloatingPointError(f"Nonfinite fitted predictions: {tag}")
    selected = next(row for row in rows if row["selected"])
    log("Fit", f"{tag}: {selected['parameter']}={selected['value']}, "
        f"valid MSE={selected['valid_mse']:.4f}")
    return final, pd.DataFrame(rows)


