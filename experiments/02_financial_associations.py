def parse_month(series):
    if isinstance(series.dtype, pd.PeriodDtype):
        return series.astype("period[M]")
    text = series.astype(str).str.replace(r"\.0$", "", regex=True)
    if text.str.fullmatch(r"\d{6}").all():
        parsed = pd.to_datetime(text, format="%Y%m", errors="raise")
    elif text.str.fullmatch(r"\d{8}").all():
        parsed = pd.to_datetime(text, format="%Y%m%d", errors="raise")
    else:
        parsed = pd.to_datetime(text, errors="raise")
    return parsed.dt.to_period("M")

