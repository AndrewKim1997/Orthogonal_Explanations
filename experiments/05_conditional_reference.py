def fit_empirical_preprocessor(x, seed):
    imputer = SimpleImputer(strategy="median")
    filled = imputer.fit_transform(x)
    transformer = QuantileTransformer(n_quantiles=min(1000, len(x)), output_distribution="normal",
        subsample=min(100000, len(x)), random_state=seed)
    transformer.fit(filled)
    return imputer, transformer


