def read_french_monthly(path, columns, value_weighted=False):
    with zipfile.ZipFile(path) as archive:
        members = [n for n in archive.namelist() if n.lower().endswith(".csv") and "__MACOSX" not in n]
        if len(members) != 1:
            raise ValueError(f"Expected one CSV in {path.name}.")
        content = archive.read(members[0]).decode("utf-8-sig", errors="replace")
    armed = not value_weighted
    header, dates, values = None, [], []
    for line in content.splitlines():
        title = re.sub(r"[-\s]+", " ", line.lower()).strip()
        if value_weighted and all(word in title for word in ["value", "weighted", "monthly"]):
            armed = True
            continue
        if not armed:
            continue
        fields = [s.strip() for s in next(csv.reader([line]))] if line.strip() else []
        while len(fields) > columns + 1 and fields[-1] == "":
            fields.pop()
        first = fields[0] if fields else ""
        if re.fullmatch(r"\d{6}", first):
            if header is None or len(fields) != columns + 1:
                raise ValueError(f"Unexpected monthly row in {path.name}.")
            dates.append(first)
            values.append([float(s) if s else np.nan for s in fields[1:]])
        elif dates:
            break
        elif len(fields) == columns + 1 and first.lower() in {"", "date"} and all(fields[1:]):
            header = fields[1:]
    if not dates or header is None or len(set(header)) != columns:
        raise ValueError(f"Required monthly table missing from {path.name}.")
    array = np.asarray(values, float)
    array[np.isclose(array, -99.99, rtol=0, atol=1e-8) | np.isclose(array, -999, rtol=0, atol=1e-8)] = np.nan
    frame = pd.DataFrame(array / 100.0, index=pd.to_datetime(dates, format="%Y%m").to_period("M"), columns=header)
    if frame.index.duplicated().any():
        raise ValueError(f"Duplicate French source months: {path.name}")
    return frame.sort_index()


def month_end_prices(series, calendar):
    """Use observed month-end quotes; reject quotes older than seven calendar days."""
    series = series.replace([np.inf, -np.inf], np.nan).where(series > 0).dropna().sort_index()
    if series.index.duplicated().any():
        raise ValueError("Duplicate source dates for an asset.")
    dates = pd.Series(series.index, index=series.index)
    periods = series.index.to_period("M")
    prices = series.groupby(periods).last().reindex(calendar)
    last_dates = dates.groupby(periods).last().reindex(calendar)
    age = (pd.Series(calendar.to_timestamp(how="end").normalize(), index=calendar) - last_dates).dt.days
    return prices.where(age <= CFG["max_month_end_age_days"])


def parse_kdd17_dates(values, ticker):
    """Read ISO and US slash dates, including both formats within one CSV."""
    text = values.astype("string").str.strip()
    iso = text.str.fullmatch(r"\d{4}-\d{2}-\d{2}", na=False)
    us = text.str.fullmatch(r"\d{1,2}/\d{1,2}/\d{4}", na=False)
    unsupported = ~(iso | us)
    if unsupported.any():
        examples = text.loc[unsupported].head(5).tolist()
        raise ValueError(f"Unsupported KDD17 date strings in {ticker}: {examples}")
    dates = pd.Series(pd.NaT, index=values.index, dtype="datetime64[ns]")
    try:
        if iso.any():
            dates.loc[iso] = pd.to_datetime(text.loc[iso], format="%Y-%m-%d", errors="raise")
        if us.any():
            dates.loc[us] = pd.to_datetime(text.loc[us], format="%m/%d/%Y", errors="raise")
    except (ValueError, OverflowError) as exc:
        raise ValueError(f"Invalid calendar date in KDD17 source file {ticker}.") from exc
    return dates


